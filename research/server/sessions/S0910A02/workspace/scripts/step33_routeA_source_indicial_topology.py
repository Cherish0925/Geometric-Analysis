# Indicial inventory for the scalar/vector-free radial power model.
# For a symmetric 2-tensor mode h=r^alpha phi(theta) on a Ricci-flat cone C(Y^3),
# the Wronskian boundary form between alpha and beta radial powers has leading
# exponent alpha+beta+2 in dimension 4: area r^3 times (r^alpha * d_r r^beta - ...)
