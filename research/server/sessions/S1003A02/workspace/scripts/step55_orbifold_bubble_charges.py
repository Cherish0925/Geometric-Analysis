#!/usr/bin/env python3
"""Step 55: two-orientation P-charges of ALE bubbles with lens-space (and ADE) ends, k=1 orbifold gate.

Conventions (fixed by EH, A_3, Burns checks below).  An ALE end C^2/Gamma, Gamma=Z_n generated by (z1,z2)->(zeta z1, zeta^q z2),
zeta=e^{2 pi i/n}, seen in the orientation of N (= orientation of M).  eta(n,q) := -4 s(q,n), s = Dedekind sum.
For a smooth ALE N with Euler characteristic chi, signature tau, end group of order |Gamma|:
   P(N) = 4 int|W^+|^2 + (1/12) int s^2 + 8 pi^2 c_+(N),   c_+ = 2/|Gamma| - 2 chi - 3 tau - 3 eta
   P(N) = 4 int|W^-|^2 + (1/12) int s^2 + 8 pi^2 c_-(N),   c_- = 2/|Gamma| - 2 chi + 3 tau + 3 eta
so P(N) >= 8 pi^2 max(c_+, c_-, 0).  Gluing ledger: T_+^orb(V) = T_+(M) + c_+(N) for the bulk orbifold V.
Also checks numerically P(LeBrun O(-n)) = 8 pi^2 (n-2)^2/n from the explicit metric.
Output: workspace/data/step55_orbifold_bubble_charges.json
"""
import json, os
from fractions import Fraction as F
from math import gcd
import sympy as sp
import numpy as np
from scipy.integrate import quad


def saw(x):  # ((x)) sawtooth on rationals
    if x.denominator == 1:
        return F(0)
    return x - (x.numerator // x.denominator) - F(1, 2)


def dedekind(h, k):
    return sum((saw(F(r, k)) * saw(F(h * r, k)) for r in range(1, k)), F(0))


def eta(n, q):
    return -4 * dedekind(q % n, n) if n > 1 else F(0)


def charges(n, q, chi, tau, order=None, et=None):
    order = n if order is None else order
    e = eta(n, q) if et is None else et
    cp = F(2, order) - 2 * chi - 3 * tau - 3 * e
    cm = F(2, order) - 2 * chi + 3 * tau + 3 * e
    return cp, cm


out = {}
# ---- convention checks
chk = {
    'Burns O(-1): n=1,chi=2,tau=-1': charges(1, 1, 2, -1),
    'EH O(-2): n=2,q=1,chi=2,tau=-1': charges(2, 1, 2, -1),
    'A3 hyperkahler: n=4,q=3,chi=4,tau=-3': charges(4, 3, 4, -3),
    'A_{n-1} n=7,q=6,chi=7,tau=-6': charges(7, 6, 7, -6),
    'EH/Z2 (T-type 1/4(1,1)) complex orientation: n=4,q=1,chi=1,tau=0': charges(4, 1, 1, 0),
}
out['convention_checks'] = {k: [str(v[0]), str(v[1])] for k, v in chk.items()}
assert chk['Burns O(-1): n=1,chi=2,tau=-1'][0] == 1
assert chk['EH O(-2): n=2,q=1,chi=2,tau=-1'][0] == 0
assert chk['A3 hyperkahler: n=4,q=3,chi=4,tau=-3'][0] == 0
assert chk['A_{n-1} n=7,q=6,chi=7,tau=-6'][0] == 0
assert chk['EH/Z2 (T-type 1/4(1,1)) complex orientation: n=4,q=1,chi=1,tau=0'] == (0, -3)

# ---- LeBrun O(-n) charge formula and numerical P from the metric
r = sp.symbols('r', positive=True)
nn = sp.symbols('n', positive=True)
V = 1 + (nn - 2) / r**2 + (1 - nn) / r**4
A = r; B = r; C = r * sp.sqrt(V)
dt = lambda f: sp.sqrt(V) * sp.diff(f, r)   # d/d(proper distance)


def Rii(X, Y, Z):
    return -dt(dt(X)) / X - dt(X) / X * (dt(Y) / Y + dt(Z) / Z) + 2 * (X**4 - (Y**2 - Z**2)**2) / (X**2 * Y**2 * Z**2)


R00 = -(dt(dt(A)) / A + dt(dt(B)) / B + dt(dt(C)) / C)
Rs = [R00, Rii(A, B, C), Rii(B, C, A), Rii(C, A, B)]
scal = sp.simplify(sum(Rs))
ric2 = sum(R**2 for R in Rs)
f = sp.lambdify((r, nn), ric2 * r**3, 'numpy')
leb = {}
for n in range(1, 9):
    val, err = quad(lambda x: f(x, n), 1, np.inf, limit=400)
    P_over_8pi2 = (2 * np.pi**2 / n) * val / (8 * np.pi**2)
    formula = charges(n, 1, 2, -1)[0]
    leb[n] = {'P/8pi^2 numeric': P_over_8pi2, 'c_+ formula (n-2)^2/n': str(formula), 'float': float(formula),
              'agree': abs(P_over_8pi2 - float(formula)) < 1e-7}
out['lebrun_scalar_curvature_symbolic'] = str(scal)
out['lebrun_O(-n)_P'] = leb

# ---- b2=1 bubbles with cyclic end: class m E, square -m^2; simply connected => n=m^2, q a unit square mod n
b2one = []
for m in range(1, 13):
    n = m * m
    units = [q for q in range(1, n + 1) if gcd(q, n) == 1] if n > 1 else [1]
    sq = sorted({(u * u) % n if n > 1 else 1 for u in units})
    for q in sq:
        cp, cm = charges(n, q, 2, -1)
        b2one.append({'m': m, 'n': n, 'q': q, 'c+': str(cp), 'c-': str(cm), 'max': float(max(cp, cm, 0)),
                      'excluded_by_charge(max>=1)': max(cp, cm) >= 1})
out['b2_one_cyclic_simply_connected'] = b2one
out['b2_one_cyclic_exceptions'] = [d for d in b2one if not d['excluded_by_charge(max>=1)']]

# ---- b2=1 with noncyclic SU(2) ends: eta from Kronheimer P=0: eta=(2/|G|+r-2)/3 (r=ADE rank)
ade = {}
for name, order, rank, H1 in ([('D%d' % k, 4 * (k - 2), k, 'Z4' if k % 2 else 'Z2xZ2') for k in range(4, 14)] +
                              [('E6', 24, 6, 'Z3'), ('E7', 48, 7, 'Z2'), ('E8', 120, 8, '0')]):
    et = (F(2, order) + rank - 2) / 3
    cp, cm = charges(0, 0, 2, -1, order=order, et=et)
    ade[name] = {'|Gamma|': order, 'H1(end)': H1, 'c+': str(cp), 'c-': str(cm), 'max': float(max(cp, cm, 0)),
                 'excluded_by_charge': max(cp, cm) >= 1}
out['b2_one_ADE_end_in_M_orientation'] = ade

# ---- rational-ball bubbles chi=1, tau=0, n=m^2, all q; mark T-type q=m k-1 (Lisca family 1 / Wahl)
rb = []
for m in range(2, 11):
    n = m * m
    tq = {(m * k - 1) % n for k in range(1, m + 1) if gcd(m, k) == 1}
    tq |= {pow(x, -1, n) for x in list(tq)}
    for q in range(1, n):
        if gcd(q, n) != 1:
            continue
        cp, cm = charges(n, q, 1, 0)
        rb.append({'m': m, 'n': n, 'q': q, 'T_type_(q=mk-1 or inverse)': q in tq,
                   'c+': str(cp), 'c-': str(cm), 'max': float(max(cp, cm, 0)),
                   'excluded_by_charge': max(cp, cm) >= 1})
out['rational_ball_lens'] = rb
out['rational_ball_T_type_summary'] = [{'n': d['n'], 'q': d['q'], 'c+': d['c+'], 'c-': d['c-']} for d in rb
                                       if d['T_type_(q=mk-1 or inverse)']]
tt = [d for d in rb if d['T_type_(q=mk-1 or inverse)']]
out['T_type_zero_charge_in_one_orientation'] = all(F(d['c+']) == 0 or F(d['c-']) == 0 for d in tt)
out['T_type_other_orientation_equals_-4(1-1/m^2)'] = all(
    {F(d['c+']), F(d['c-'])} == {F(0), F(-4) * (1 - F(1, d['m']**2))} for d in tt)
out['rational_ball_max_charge_over_all_q_by_m'] = {m: max(d['max'] for d in rb if d['m'] == m) for m in range(2, 11)}

p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'step55_orbifold_bubble_charges.json')
with open(p, 'w') as fh:
    json.dump(out, fh, indent=1, default=str)
print(json.dumps({k: out[k] for k in ['convention_checks', 'lebrun_scalar_curvature_symbolic', 'lebrun_O(-n)_P',
                                      'b2_one_cyclic_exceptions', 'b2_one_ADE_end_in_M_orientation',
                                      'rational_ball_T_type_summary', 'T_type_zero_charge_in_one_orientation',
                                      'T_type_other_orientation_equals_-4(1-1/m^2)',
                                      'rational_ball_max_charge_over_all_q_by_m']}, indent=1, default=str))
