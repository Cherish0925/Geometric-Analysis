"""Step 40: harmonic-class compatibility and exceptional-period stiffness of the perpendicular cell.

Setting (peer slot order, Ric_CH=-6g profile scale):
    g = dx^2/(4G) + H_ij(x) s_i s_j,  H = diag(F, x, x e^w) at the diagonal cell,
    slot 1 = collapsing (bolt) circle, slot 3 = CH Kahler fibre f.
With d s_i = 2 s_j ^ s_k (cyclic), an SU(2)-invariant closed 2-form is d(sum_i phi_i s_i), and it is
self-dual iff  (d/dt) phi = (2/sqrt(det H)) H phi .   (*)
For the diagonal cell the canonical form is phi=(0,0,phi_f), phi_f'/phi_f=2H_33/sqrt(det H),
phi_f(collar)=X (host Kahler form).  Its exceptional period is int_E = 2 pi phi_1(bolt) = 0.

For an invariant variation dH supported in the cell (collar fixed), (*) integrated backward from the
fixed collar value gives a smooth SD form; the fixed (pullback) class stays self-dual iff the new
phi_1(bolt)=0.  To first order only dH_13 enters:
    delta phi_1(0) = - psi_+(0) int_0^{t_c} 2 dH_13 phi_f /(sqrt(det H) psi_+) dt,
    psi_+ = exp int 2 H_11/sqrt(det H) dt  (psi_+(collar)=1),
and 1/psi_+ is the potential of the bolt-regular invariant ASD harmonic form d(psi_- s_1).
dH_12 never enters; dH_23 produces a regular phi_2 = O(t^2) (no obstruction); diagonal dH none.

The script
  (1) evaluates the period functional on the Step-21 basis of the h13 Hessian block
      (k_13 = N_13 u^2(1-u)^3 T_m(2u-1), N_13=x sqrt(1+x), plus bolt rotation theta=psi*chi);
  (2) checks the closed-form gauge identity  int 2(H11-H33) phi/(sqrt(det) psi_+) dt = -phi(c)/psi_+(c);
  (3) checks linearity against a finite-amplitude nonlinear integration of (*) (exact rotation);
  (4) computes the minimal second-order J6 cost of opening exceptional period t=int_E Omega:
      Delta J/(8 pi^2) = t^2 / (2 L^T H^{-1} L),  L = pi * d phi_1(0)/dc  (t = int_E Omega, Omega=(1/2)d(phi s)),
      a Ritz (upper) value within the SU(2)-invariant h13 block, compared with the Kahler slope 6/pi.
Floating evidence; the Hessians are those of Step 21 (data/su2_offdiag/hessR_*.json).

Usage: python step40_harmonic_class_period.py HESS.json [...] --out OUT.json
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from perp_dual_cost import DualCell, load_record, seed_vector  # noqa: E402
from o11_perp_cell import cheb  # noqa: E402


def setup(rec):
    deg = int(rec["deg"]); x0 = float(rec["x0"]); X = float(rec["X"])
    c = DualCell(x0, X, deg, deg, 200); c.aligned = False; c.wpow = 2
    z = jnp.asarray(np.asarray(seed_vector(c, rec), float))
    base = c.prof_factory(z)
    return c, base, x0, X


def grid(x0, X, n_geo=20000, n_lin=200000):
    u = np.concatenate([np.geomspace(1e-11, 1e-3, n_geo, endpoint=False), np.linspace(1e-3, 1.0, n_lin)])
    return u, x0 * np.exp(np.log(X / x0) * u)


def cumtrap(f, u):
    out = np.zeros_like(f)
    out[1:] = np.cumsum(0.5 * (f[1:] + f[:-1]) * np.diff(u))
    return out


def trap(f, u):
    return float(np.sum(0.5 * (f[1:] + f[:-1]) * np.diff(u)))


def analyse(hpath, nl_amp=(1e-4, 3e-4, 1e-3)):
    d = json.load(open(hpath))
    rec_path = (HERE / d["record"]).resolve()
    rec = load_record(rec_path)
    c, base, x0, X = setup(rec)
    ell = np.log(X / x0)
    n = int(d["n"])
    u, x = grid(x0, X)
    G, H = [np.asarray(v) for v in jax.vmap(base)(jnp.asarray(x))]
    dtdu = ell * x / (2 * np.sqrt(G))
    H11, H22, H33 = H[:, 0, 0], H[:, 1, 1], H[:, 2, 2]
    sq = np.sqrt(H11 * H22 * H33)
    offmax = float(np.max(np.abs(H - np.einsum('ij,kj->kij', np.eye(3), np.stack([H11, H22, H33], 1)))))
    lpsi = cumtrap(2 * H11 / sq * dtdu, u); lpsi -= lpsi[-1]
    lphi = cumtrap(2 * H33 / sq * dtdu, u); lphi -= lphi[-1]
    psi_p = np.exp(lpsi); phi = X * np.exp(lphi)
    psi0 = psi_p[0]
    w = 2 * phi / (sq * psi_p) * dtdu          # density in u of the period functional
    env = u**2 * (1 - u)**3
    N13 = x * np.sqrt(1 + x)
    chi = (1 - u)**3 * (1 + 3 * u + 6 * u * u)
    T = np.polynomial.chebyshev.chebvander(2 * u - 1, n - 1)
    ell_m = np.array([-psi0 * trap(N13 * env * T[:, m] * w, u) for m in range(n)])
    ell_rot = -psi0 * trap(chi * (H11 - H33) * w, u)
    # gauge identity for constant rotation: int (H11-H33) w du = -phi(c)/psi_+(c) = -X
    gauge_lhs = trap((H11 - H33) * w, u)
    ell_vec = np.concatenate([ell_m, [ell_rot]])
    # Omega = (1/2) d(phi_i s_i) and int_E d(phi_1 s_1) = 2 pi phi_1(0), so t = int_E Omega = pi phi_1(0).
    Lt = np.pi * ell_vec                        # d(period t)/d(coefficient)  (corrected after TTCS step40)

    # Phi(t) = psi_+(0) phi/psi_+ : the period generated by a unit rotation step at radius t
    Phi = psi0 * phi / psi_p
    marks = {}
    for xm in [0.05, 0.1, 0.3, 1.0, 3.0, 10.0, 30.0, X]:
        i = min(np.searchsorted(x, xm), len(x) - 1)
        marks[f"x={xm:g}"] = float(Phi[i])
    # where does the bolt-rotation period come from: theta' Phi density
    dens_rot = -psi0 * chi * (H11 - H33) * w
    cum = cumtrap(dens_rot, u)
    frac = {}
    for xm in [0.1, 0.3, 1.0, 3.0, 10.0, 30.0]:
        i = min(np.searchsorted(x, xm), len(x) - 1)
        frac[f"x<{xm:g}"] = float(cum[i] / cum[-1])

    # nonlinear check on (*) with an exact rotation theta=psi*chi and a k13 bump c0
    def phi1_bolt(psi_amp, cvec):
        R = np.zeros((len(u), 3, 3))
        b = psi_amp * chi
        cb, sb = np.cos(b), np.sin(b)
        R[:, 0, 0] = cb; R[:, 2, 2] = cb; R[:, 0, 2] = -sb; R[:, 2, 0] = sb; R[:, 1, 1] = 1
        Hn = np.einsum('kij,kjl,kml->kim', R, H, R)
        k13 = N13 * env * (T @ cvec)
        Hn[:, 0, 2] += k13; Hn[:, 2, 0] += k13
        sqn = np.sqrt(np.linalg.det(Hn))
        M = 2 * Hn / sqn[:, None, None] * dtdu[:, None, None]   # d phi/du = M phi
        y = np.array([0.0, 0.0, X])
        # backward RK2 (trapezoid/Heun) on the fine grid
        for k in range(len(u) - 1, 0, -1):
            h = u[k - 1] - u[k]
            k1 = M[k] @ y
            yp = y + h * k1
            k2 = M[k - 1] @ yp
            y = y + 0.5 * h * (k1 + k2)
        return y
    nl = []
    for a in nl_amp:
        cv = np.zeros(n); cv[0] = a
        yr = phi1_bolt(a, np.zeros(n)); yc = phi1_bolt(0.0, cv); y0 = phi1_bolt(0.0, np.zeros(n))
        nl.append(dict(amp=a, rot_phi1=float(yr[0]), rot_lin=float(a * ell_rot),
                       k0_phi1=float(yc[0]), k0_lin=float(a * ell_m[0]),
                       base_phi=[float(v) for v in y0]))

    Hb = np.array(d["H_blocks"]["h13"])
    Hb = 0.5 * (Hb + Hb.T)
    ev = np.linalg.eigvalsh(Hb)
    Hinv_L = np.linalg.solve(Hb, Lt)
    compl = float(Lt @ Hinv_L)                  # t^2 / (2 * Delta J) inverse stiffness
    K = 1.0 / compl                             # Delta J/(8pi^2) = K t^2/2
    cstar = Hinv_L / compl                      # optimal unit-period direction
    # period stiffness of pure bolt rotation and of rotation with period-preserving relaxation
    A = Hb[:n, :n]; bvec = Hb[:n, n]
    schur = float(Hb[n, n] - bvec @ np.linalg.solve(A, bvec))
    # Delta J along fixed-period hyperplane: restricted minimum eigenvalue
    Q, _ = np.linalg.qr(np.column_stack([Lt / np.linalg.norm(Lt), np.eye(n + 1)]))
    P = Q[:, 1:n + 1]
    ev_hyper = np.linalg.eigvalsh(P.T @ Hb @ P)
    # crossover with the Kahler aligned linear slope 6/pi (profile scale)
    t_cross = 2 * (6 / np.pi) / K
    return {
        "hessian": str(hpath), "record": str(rec_path), "x0": x0, "X": X, "n": n,
        "J0": d["J0"], "diag_check_offdiag_max": offmax,
        "psi_plus_bolt": float(psi0), "phi_collar": float(phi[-1]),
        "phi_over_t2_near_bolt_proxy": float(phi[5] / (x[5] - x0)),
        "gauge_identity": {"lhs": gauge_lhs, "rhs": -float(X), "rel_err": abs(gauge_lhs + X) / X},
        "Phi_profile": marks,
        "bolt_rotation_period_cumulative_fraction": frac,
        "ell_rot_dphi1_dpsi": float(ell_rot),
        "ell_basis": [float(v) for v in ell_m],
        "nonlinear_check": nl,
        "h13_block_eigs_min3": [float(v) for v in ev[:3]],
        "schur_bolt_rotation": schur,
        "dperiod_dpsi_pure_rotation": float(np.pi * ell_rot),
        "period_convention": "t=int_E Omega=pi*phi_1(0), Omega=(1/2)d(phi s)",
        "inverse_period_stiffness_LtHinvLt": compl,
        "period_stiffness_K": K,
        "DeltaJ_over_8pi2_per_t2": K / 2,
        "ric_minus_one_scale": {"t_g_equals_6t": True, "DeltaJ_per_tg2": K / 72},
        "optimal_direction_rotation_component": float(cstar[n]),
        "fixed_period_hyperplane_min_eigs": [float(v) for v in ev_hyper[:3]],
        "kahler_aligned_slope_profile_scale": 6 / np.pi,
        "t_crossover_quadratic_equals_kahler_linear": float(t_cross),
        "scope": "Ritz value in SU(2)-invariant h13 block at fixed collar; second order; floating",
    }


def functional_only(rec_path):
    """Period functional of the pure bolt rotation theta=chi on a cell record without a Hessian
    (used for the certified x0=.03, X=128 profile).  Returns pi*dphi_1(0)/dpsi and Phi."""
    rec = load_record(rec_path)
    if "deg" not in rec:
        rec = dict(rec, deg=int(rec.get("degU", 6)))
    c, base, x0, X = setup(rec)
    u, x = grid(x0, X)
    G, H = [np.asarray(v) for v in jax.vmap(base)(jnp.asarray(x))]
    dtdu = np.log(X / x0) * x / (2 * np.sqrt(G))
    H11, H22, H33 = H[:, 0, 0], H[:, 1, 1], H[:, 2, 2]
    sq = np.sqrt(H11 * H22 * H33)
    lpsi = cumtrap(2 * H11 / sq * dtdu, u); lpsi -= lpsi[-1]
    lphi = cumtrap(2 * H33 / sq * dtdu, u); lphi -= lphi[-1]
    psi_p = np.exp(lpsi); phi = X * np.exp(lphi)
    w = 2 * phi / (sq * psi_p) * dtdu
    chi = (1 - u)**3 * (1 + 3 * u + 6 * u * u)
    ell_rot = -psi_p[0] * trap(chi * (H11 - H33) * w, u)
    gauge = trap((H11 - H33) * w, u)
    dens = -psi_p[0] * chi * (H11 - H33) * w
    return {"record": str(rec_path), "x0": x0, "X": X, "psi_plus_bolt": float(psi_p[0]),
            "dphi1_dpsi": float(ell_rot), "dt_dpsi": float(np.pi * ell_rot),
            "density_sign_min_max": [float(dens.min()), float(dens.max())],
            "gauge_identity_rel_err": abs(gauge + X) / X,
            "min_H11_minus_H33": float(np.min(H11 - H33)), "max_H11_minus_H33": float(np.max(H11 - H33))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("hess", nargs="*")
    ap.add_argument("--record", action="append", default=[])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.record:
        res = [functional_only(Path(r)) for r in a.record]
        Path(a.out).write_text(json.dumps(res, indent=1) + "\n")
        print(json.dumps(res, indent=1))
        return
    res = [analyse(Path(h)) for h in a.hess]
    Path(a.out).write_text(json.dumps(res, indent=1) + "\n")
    for r in res:
        print(json.dumps({k: r[k] for k in ["hessian", "n", "gauge_identity", "psi_plus_bolt", "ell_rot_dphi1_dpsi",
                                            "schur_bolt_rotation", "period_stiffness_K", "DeltaJ_over_8pi2_per_t2",
                                            "t_crossover_quadratic_equals_kahler_linear",
                                            "fixed_period_hyperplane_min_eigs", "Phi_profile",
                                            "bolt_rotation_period_cumulative_fraction", "nonlinear_check"]}, indent=1))


if __name__ == "__main__":
    main()
