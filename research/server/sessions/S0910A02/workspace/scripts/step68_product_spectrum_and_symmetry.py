#!/usr/bin/env python3
"""Step 68: symmetry and TT-spectrum checks for (S^2 x S^2)/Z2.

This script is not a numerical proof of the mixed obstruction coefficients.  It
records exact low-spectrum and symmetry facts that gate the Ozuch finite-dimensional
computation:
  * the orientation reversing reflection c commutes with the quotient rotation and
    fixes the four A1 nodes, so it exchanges compatible and reversed data nodewise;
  * the Ozuch operator P = 1/2 nabla^*nabla - Rcirc has no TT kernel on the
    product orbifold, but has the invariant relative-scale negative mode;
  * an eigenfunction-value Green sum is the wrong object for distant-bubble
    coupling; the needed object is a second jet at the receiving node of the
    P-harmonic tensor with a prescribed r^{-4} quadrupole at the source node.
"""
from __future__ import annotations

import itertools
import json
from pathlib import Path
from fractions import Fraction

WORKSPACE = Path(__file__).resolve().parents[1]
OUT = WORKSPACE / "data" / "step68_product_spectrum_and_symmetry.json"
OUT.parent.mkdir(parents=True, exist_ok=True)

# ---------------------------------------------------------------------------
# A. Node combinatorics and reflection c.
# ---------------------------------------------------------------------------
# Nodes are fixed points of rho(z)=-z on each CP^1 coordinate: 0 and infinity.
# Use signs +1=N/0, -1=S/infty only as labels.
nodes = {
    "p1": ("N", "N"),
    "p2": ("N", "S"),
    "p3": ("S", "N"),
    "p4": ("S", "S"),
}
node_names = list(nodes.keys())

def complement(subset):
    return tuple(sorted(set(node_names) - set(subset)))

# Square symmetries of the four nodes generated by swapping factors and flipping
# N<->S in either factor.  This is a conservative node-level symmetry ledger;
# smooth seam/spin data may refine the r=2 classes, so we do not quotient those
# away in the final mathematical statement without checking gluing maps.
def transform_node(coord, flip1=False, flip2=False, swap=False):
    a, b = coord
    if flip1:
        a = "S" if a == "N" else "N"
    if flip2:
        b = "S" if b == "N" else "N"
    if swap:
        a, b = b, a
    return (a, b)

coord_to_name = {v: k for k, v in nodes.items()}
perms = []
for flip1, flip2, swap in itertools.product([False, True], repeat=3):
    p = {name: coord_to_name[transform_node(coord, flip1, flip2, swap)] for name, coord in nodes.items()}
    if p not in perms:
        perms.append(p)

def orbit(subset):
    S = set(subset)
    reps = set()
    for p in perms:
        reps.add(tuple(sorted(p[x] for x in S)))
    return sorted(reps)

pattern_orbits = {}
for r in range(5):
    seen = set()
    classes = []
    for S in itertools.combinations(node_names, r):
        if S in seen:
            continue
        orb = orbit(S)
        seen.update(orb)
        classes.append({"representative": S, "orbit": orb, "complement": complement(S), "complement_orbit": orbit(complement(S))})
    pattern_orbits[f"r={r}"] = classes

# Reflection c:(z,w)->(conjugate(z),w) reverses the orientation of the first S^2,
# commutes with rho(z)=-z, and fixes 0,infty.  In a local oriented orthonormal
# product frame (e1,e2 | e3,e4) with c_* e2=-e2, it swaps the chiral bundles.
# We record the chiral-basis action up to harmless signs for a conventional basis.
reflection_c = {
    "map": "c:(z,w)->(conjugate(z),w)",
    "commutes_with_rho": True,  # conj(-z)=-conj(z)
    "fixes_nodes": node_names,
    "orientation": "reverses product orientation (reverses first S^2 only)",
    "pattern_action_on_reversed_set": "S -> complement(S)",
    "chiral_action_conventional_basis": {
        "omega1_plus": "- omega1_minus",
        "omega2_plus": "- omega2_minus (up to basis convention)",
        "omega3_plus": "+ omega3_minus (up to basis convention)",
        "Lambda_plus": "Lambda_minus",
        "Lambda_minus": "Lambda_plus",
    },
}

# ---------------------------------------------------------------------------
# B. Ozuch/Kroencke convention check for h_rel = g1 - g2.
# ---------------------------------------------------------------------------
# Work in an orthonormal frame with indices 0,1 on factor 1 and 2,3 on factor 2.
# Each factor is a round S^2 with sectional curvature Lambda, hence Ric=Lambda g.
# For h_rel = diag(1,1,-1,-1), Rcirc(h_rel)=Lambda*h_rel, so Ozuch P=-Lambda*h_rel.
# This is the unit test for the convention used in Ozuch/LeBrun-Ozuch.  Other
# authors use Delta_E=2P or second-variation operators with extra factors.
Lambda = Fraction(1, 1)
h_rel = [Fraction(1), Fraction(1), Fraction(-1), Fraction(-1)]
Rcirc_h = [Lambda * x for x in h_rel]
P_h = [-x for x in Rcirc_h]  # nabla h=0
DeltaE_h = [2 * x for x in P_h]
convention_test = {
    "tensor": "h_rel = g1 - g2 = diag(1,1,-1,-1)",
    "Rcirc_h_over_h": str(Lambda),
    "Ozuch_P_equals": "-Lambda * h_rel",
    "Ozuch_P_components_for_Lambda_1": [str(x) for x in P_h],
    "Kroencke_Delta_E_equals": "-2*Lambda * h_rel (since Delta_E=2P)",
    "Kroencke_Delta_E_components_for_Lambda_1": [str(x) for x in DeltaE_h],
    "note_on_minus_4Lambda": "A -4*Lambda unit test is not the Ozuch P convention; it can only refer to a differently normalized Einstein/second-variation operator or to a metric variation scaled by an extra factor.",
}

# ---------------------------------------------------------------------------
# C. TT-kernel computation on S^2 x S^2 and quotient.
# ---------------------------------------------------------------------------
# Factor facts for S^2_Ric=Lambda:
# scalar eigenvalues lambda_l = Lambda*l(l+1), multiplicity 2l+1.
# There are no factor TT tensors on S^2 (holomorphic quadratic differentials on CP^1 vanish).
# The only possible product TT zero modes from scalar sectors would use lambda_l=2Lambda,
# i.e. l=1.  In dimension 2, Hess(f)=-Lambda*f*g for l=1, so the standard Koiso
# product IED formula degenerates to the zero tensor.  Direct TT equations for
# a*f*g1 + b*f*g2 give a+b=0 from trace and a=0 from divergence, hence b=0.

def scalar_eigen(l: int) -> int:
    return l * (l + 1)  # in units of Lambda

low_scalar = [{"l": l, "lambda_over_Lambda": scalar_eigen(l), "multiplicity": 2*l+1} for l in range(6)]

kernel_argument = {
    "factor": "S^2 with Ric=Lambda*g",
    "factor_TT_kernel_dim": 0,
    "lambda_l_over_Lambda": "l(l+1)",
    "only_scalar_value_equal_2Lambda": "l=1, multiplicity 3 on each factor",
    "l1_hessian_identity": "Hess(f) = -Lambda*f*g for first spherical harmonics",
    "scalar_zero_mode_TT_check": {
        "ansatz": "h = a*f*g1 + b*f*g2 (+ c*Hess f, but Hess f is proportional to f*g1 for l=1)",
        "trace_condition": "a_eff + b = 0",
        "divergence_condition": "a_eff = 0",
        "conclusion": "a_eff=b=0; scalar full-kernel modes do not give TT tensors on S^2 x S^2",
    },
    "mixed_one_form_sector": "Rcirc=0 on mixed tensors and the rough 1-form spectrum on each S^2 is >= Lambda, so Ozuch P >= Lambda > 0 there",
    "parallel_relative_scale_mode": {
        "descends_to_orbifold": True,
        "TT": True,
        "Ozuch_P_eigenvalue_over_Lambda": -1,
        "Kroencke_Delta_E_eigenvalue_over_Lambda": -2,
        "role": "unique low negative mode / saddle direction, bounded away from 0",
    },
    "TT_kernel_dim_product": 0,
    "TT_kernel_dim_Z2_orbifold": 0,
    "reason_quotient_no_new_kernel": "an orbifold-smooth tensor on the quotient pulls back to a smooth sigma-invariant tensor on the cover; the cover TT kernel is zero",
    "spectral_gap_around_zero_in_Ozuch_units_at_least": "Lambda (from h_rel at -Lambda and mixed/next positive sectors >= Lambda or 2Lambda)",
}

# A small parity ledger for future harmonic sums.  Under rho(z)=-z, scalar
# Y_l^m gets (-1)^m.  Product quotient keeps m1+m2 even.  Tensor/vector harmonics
# need their spin-weighted analogues, but this scalar parity is a useful bug check.
parity_ledger = []
for l1 in range(4):
    for m1 in range(-l1, l1+1):
        for l2 in range(4):
            for m2 in range(-l2, l2+1):
                if m1 + m2 == 0 and l1 <= 2 and l2 <= 2:  # compact sample visible in data
                    parity_ledger.append({
                        "l1": l1, "m1": m1, "l2": l2, "m2": m2,
                        "rho_product_sign": 1 if (m1 + m2) % 2 == 0 else -1,
                        "scalar_descends": ((m1 + m2) % 2 == 0),
                    })

# ---------------------------------------------------------------------------
# D. Correct Green/multipole object.
# ---------------------------------------------------------------------------
multipole_warning = {
    "wrong_object": "bare value sum Sum psi_l(p_i) psi_l(p_j)/lambda_l",
    "why_wrong": "distant EH bubble contributes an r^{-4} TT quadrupole H^4 at p_i; its effect on node p_j is the quadratic term H_{j,2} in the Taylor expansion of the P-harmonic extension, hence a second jet at p_j after singular-part subtraction and gauge/orthogonality projection",
    "right_object_schematic": "H2_ij = (1/2) second_derivative_at_pj [ solution of P h=0 on X\\{p_i}, h~H4(zeta_i) near p_i, h perpendicular to O(g_infty), Bianchi gauge ]",
    "spectral_schematic": "contract source multipole derivatives at p_i and receiving second derivatives at p_j: Sum (D_j^2 psi_alpha)(p_j) * <psi_alpha, source_multipole_i>/lambda_alpha, not psi_alpha(p_i)psi_alpha(p_j)/lambda_alpha",
    "kernel_status_needed_for_inverse": "O(g_infty)=0 on TT for this orbifold, apart from nonzero relative-scale negative eigenmode, so no kernel unknown enters; one still must project/gauge Killing directions in the nonlinear representation",
}

result = {
    "nodes": nodes,
    "reflection_c": reflection_c,
    "pattern_orbits_under_node_symmetries": pattern_orbits,
    "convention_test_h_rel": convention_test,
    "low_scalar_spectrum_S2_units_Lambda": low_scalar,
    "TT_kernel_argument": kernel_argument,
    "scalar_parity_sample_for_sigma_quotient": parity_ledger[:80],
    "multipole_green_object": multipole_warning,
    "scope": "This establishes symmetry, convention, kernel and correct-coupling-object gates; it does not compute the actual Ozuch mixed obstruction coefficients or prove any Yau-26 branch.",
}
OUT.write_text(json.dumps(result, indent=2, ensure_ascii=False))
print(json.dumps({
    "output": str(OUT),
    "TT_kernel_dim_product": 0,
    "TT_kernel_dim_orbifold": 0,
    "Ozuch_P_h_rel_eigenvalue_over_Lambda": -1,
    "reflection_maps_r_to": "4-r",
    "independent_r_values_after_reflection": ["r=0/4 control", "r=1/3 mixed", "r=2 balanced (adjacent/diagonal seam classes may remain)"],
}, indent=2))
