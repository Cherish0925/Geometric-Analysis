"""Resolve topological/Weyl/scalar/volume channels of peer H4 cells.

Input records are generated by S1003A01/workspace/scripts/h4_perp_cell.py.
This script reconstructs the cells and integrates, in the peer Ric=-6 (s=-24)
normalization, the identities

 P-1 = 4 W+/(8pi^2) + [int s^2/12 - 48 Vol(B)]/(8pi^2),
 J-1 = 4 W+/(8pi^2) + int(s+18)^2/3/(8pi^2)
       + [36 Vol(U)-48 Vol(B)]/(8pi^2).

The chirality is fixed by demanding W+=0 on the real-hyperbolic collar.
The first identity defines/checks the relative Weyl channel from P and the
scalar-volume data; no direct coordinate Weyl evaluation is needed.
"""
from pathlib import Path
import argparse, json, sys
import numpy as np
import jax.numpy as jnp

ROOT=Path(__file__).resolve().parents[4]
PEER=ROOT/'Sessions/S1003A01/workspace/scripts'
sys.path.insert(0,str(PEER))
from h4_perp_cell import Cell


def h4_ball_volume_norm(X):
    """Vol of 0<=x<=X divided by 8*pi^2, for F=x,G=x+2x^2."""
    y=np.sqrt(1+2*X)
    return y**3/48-y/16+1/24


def analyze(path, nq=None):
    r=json.loads(Path(path).read_text())
    nq=int(nq or max(1400,int(r.get('nq',800))))
    c=Cell(float(r['x0']),float(r['X']),int(r['deg']),nq)
    z=jnp.asarray(r['z'])
    pd,sd,s,dx,F,G,w=c.fields(z)
    P=float(jnp.sum(pd*dx)); scalar_part=float(jnp.sum(sd*dx)); J=P+scalar_part
    # h4_perp Cell volume factor /(8pi^2): radial dt=dx/(2sqrtG),
    # orbit volume is 2pi^2 abc, hence dV/(8pi^2)=abc/(8sqrtG) dx.
    # The quadrature ``dx`` already contains the coordinate dx.
    x0=float(r['x0']); X=float(r['X'])
    # Reconstruct volume factor from F,G,w returned at nodes.
    vol_density=jnp.sqrt(F*jnp.exp(w)/G)*c.u*0 # dummy with correct shape
    # x is available from u: x=x0 exp(ell u).  abc=sqrt(F)*sqrt(x)*sqrt(x exp w).
    xx=x0*jnp.exp(c.ell*c.u)
    v8=jnp.sqrt(F)*xx*jnp.exp(w/2)/(8*jnp.sqrt(G))
    V=float(jnp.sum(v8*dx))
    VB=h4_ball_volume_norm(X)
    I_s2_over12=float(jnp.sum(v8*(s*s/12)*dx))
    scalar_rel=I_s2_over12-48*VB
    fourWp=P-1-scalar_rel
    sq18=float(jnp.sum(v8*((s+18)**2/3)*dx))
    rhsJ=fourWp+sq18+36*V-48*VB
    mean_s=float(jnp.sum(v8*s*dx)/V)
    rms18=float(jnp.sqrt(jnp.sum(v8*(s+18)**2*dx)/V))
    near=float(jnp.sum(v8*(jnp.abs(s+18)<=3)*dx)/V)
    return dict(source=str(path),x0=x0,X=X,deg=int(r['deg']),nq=nq,
                original_P=r.get('P'),recomputed_P=P,recomputed_J=J,
                scalar_part=scalar_part,V_norm=V,VB_norm=VB,V_over_VB=V/VB,
                I_s2_over12_norm=I_s2_over12,scalar_volume_rel_norm=scalar_rel,
                four_Wplus_rel_norm=fourWp,square_splus18_over3_norm=sq18,
                volume_channel_norm=36*V-48*VB,Jminus1_rhs=rhsJ,
                J_identity_residual=(J-1)-rhsJ,mean_scalar=mean_s,
                rms_scalar_plus18=rms18,volume_frac_abs_splus18_le3=near,
                minF=float(jnp.min(F)),minG=float(jnp.min(G)),maxabsw=float(jnp.max(jnp.abs(w))))


def main():
    ap=argparse.ArgumentParser();ap.add_argument('paths',nargs='+');ap.add_argument('--out',required=True);ap.add_argument('--nq',type=int)
    a=ap.parse_args(); rows=[analyze(p,a.nq) for p in a.paths]
    Path(a.out).write_text(json.dumps(dict(normalization='Ric=-6,s=-24; all integrals /8pi^2',rows=rows),indent=1)+'\n')
    for r in rows:
        print(json.dumps({k:r[k] for k in ['source','recomputed_P','recomputed_J','V_over_VB','four_Wplus_rel_norm','square_splus18_over3_norm','volume_channel_norm','J_identity_residual','mean_scalar','rms_scalar_plus18']}))
if __name__=='__main__':main()
