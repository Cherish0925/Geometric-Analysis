#!/usr/bin/env python3
"""
Step 99: partial normal-coordinate tensor jets omitted from Step 98.

Step 98 used h_{ab,pq}=T_{ab}(p) f_{,pq}(q) for tensor-scalar modes
h=T_A f_B or h=f_A T_B.  For zonal scalar f, f(pole) is nonzero, so the
same-factor partial jet h_{ab,pq}=T_{ab,pq} f(pole) is a possible additional
source contribution.  This script computes those partial jets in normal
coordinates on the unit S^2 for the standard electric and magnetic TT tensor
families generated by m=2 scalar harmonics, then contracts them with the Step96
receiver/source functionals.

The goal is not to re-run the heat sum; it is to decide whether the restricted
Step98 tensor-scalar model omitted a surviving H^4 source pairing.
"""
from __future__ import annotations

import importlib.util
import json
import math
import pathlib
import sys

import numpy as np
import sympy as sp

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
WS = SCRIPT_DIR.parent
DATA_DIR = WS / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)

_spec = importlib.util.spec_from_file_location("step96_ab", SCRIPT_DIR / "step96_kernel_plane_ab_map.py")
step96 = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
sys.modules[_spec.name] = step96
_spec.loader.exec_module(step96)

x, y, mu, b = sp.symbols("x y mu b")
coords = [x, y]
r2 = x*x + y*y
alpha = (sp.Integer(2) - mu) / sp.Integer(12)


def trunc(expr: sp.Expr, deg: int) -> sp.Expr:
    poly = sp.Poly(sp.expand(expr), x, y)
    out = sp.Integer(0)
    for monom, coeff in poly.terms():
        if sum(monom) <= deg:
            out += coeff * x**monom[0] * y**monom[1]
    return sp.expand(out)

# Unit S^2 normal-coordinate metric through quadratic order.
g = sp.Matrix([[1 - y*y/3, x*y/3], [x*y/3, 1 - x*x/3]])
ginv = sp.Matrix([[1 + y*y/3, -x*y/3], [-x*y/3, 1 + x*x/3]])
# complex structure chosen to be J(∂x)=∂y at the origin, through quadratic order.
# To the order needed here, sqrt(det g)=1-r^2/6 in unit-sphere normal coordinates.
sqrtdet = 1 - r2/6
omega = sp.Matrix([[0, -sqrtdet], [sqrtdet, 0]])
Jupdown = sp.Matrix([[trunc(sum(ginv[i, k]*omega[k, j] for k in range(2)), 2) for j in range(2)] for i in range(2)])

Gamma = [[[sp.Integer(0) for _ in range(2)] for _ in range(2)] for _ in range(2)]
for k in range(2):
    for i in range(2):
        for j in range(2):
            expr = sp.Integer(0)
            for l in range(2):
                expr += ginv[k, l]*(sp.diff(g[l, j], coords[i]) + sp.diff(g[l, i], coords[j]) - sp.diff(g[i, j], coords[l]))/2
            Gamma[k][i][j] = trunc(expr, 1)


def scalar_hess(f: sp.Expr) -> list[list[sp.Expr]]:
    H = [[sp.Integer(0) for _ in range(2)] for _ in range(2)]
    for a in range(2):
        for c in range(2):
            expr = sp.diff(f, coords[a], coords[c])
            for r in range(2):
                expr -= Gamma[r][a][c]*sp.diff(f, coords[r])
            H[a][c] = trunc(expr, 2)
    return H


def electric_tensor(f: sp.Expr) -> list[list[sp.Expr]]:
    H = scalar_hess(f)
    return [[trunc(H[a][c] + (mu/2)*f*g[a, c], 2) for c in range(2)] for a in range(2)]


def magnetic_tensor_lie(f: sp.Expr) -> list[list[sp.Expr]]:
    # vector X = J grad f, with J and metric to O2.
    grad_up = [trunc(sum(ginv[i, k]*sp.diff(f, coords[k]) for k in range(2)), 3) for i in range(2)]
    X = [trunc(sum(Jupdown[i, j]*grad_up[j] for j in range(2)), 3) for i in range(2)]
    h = [[sp.Integer(0) for _ in range(2)] for _ in range(2)]
    for a in range(2):
        for c in range(2):
            expr = sum(X[k]*sp.diff(g[a, c], coords[k]) for k in range(2))
            expr += sum(g[k, c]*sp.diff(X[k], coords[a]) for k in range(2))
            expr += sum(g[a, k]*sp.diff(X[k], coords[c]) for k in range(2))
            h[a][c] = trunc(expr, 2)
    return h


def partial2_tensor(T: list[list[sp.Expr]]) -> np.ndarray:
    H = np.empty((2, 2, 2, 2), dtype=object)
    for a, c, p, q in np.ndindex(2, 2, 2, 2):
        H[a, c, p, q] = sp.factor(sp.simplify(sp.diff(T[a][c], coords[p], coords[q]).subs({x: 0, y: 0})))
    return H


def embed(K2: np.ndarray, sector: str) -> np.ndarray:
    H = np.zeros((4, 4, 4, 4), dtype=float)
    for a, c, p, q in np.ndindex(2, 2, 2, 2):
        val = float(K2[a, c, p, q])
        if sector == "AA":
            H[a, c, p, q] = val
        elif sector == "BB":
            H[2+a, 2+c, 2+p, 2+q] = val
        else:
            raise ValueError(sector)
    return H


def contract(K2: np.ndarray, sector: str) -> dict:
    H = embed(K2, sector)
    return {
        "R_plus": step96.receiver_matrix(H, "plus").tolist(),
        "R_minus": step96.receiver_matrix(H, "minus").tolist(),
        "S_plus_over_pi2": step96.source_matrix_over_pi2(H, "plus").tolist(),
        "S_minus_over_pi2": step96.source_matrix_over_pi2(H, "minus").tolist(),
    }


def eval_form(K: np.ndarray, ell: int) -> np.ndarray:
    m = ell*(ell+1)
    bval = math.sqrt((2*ell+1)*m*(m-2)/(128*math.pi))
    out = np.zeros((2,2,2,2), dtype=float)
    for idx in np.ndindex(2,2,2,2):
        out[idx] = float(K[idx].subs({mu: m, b: bval}))
    return out

psi_c = b*(x*x-y*y)*(1+alpha*r2)
psi_s = b*(2*x*y)*(1+alpha*r2)
T = {
    "electric_c2": electric_tensor(psi_c),
    "electric_s2": electric_tensor(psi_s),
    "magnetic_c2": magnetic_tensor_lie(psi_c),
    "magnetic_s2": magnetic_tensor_lie(psi_s),
}
Kform = {name: partial2_tensor(tens) for name, tens in T.items()}

formula_summary = {}
for name, K in Kform.items():
    formula_summary[name] = {
        "nonzero_entries": [
            {"a": a, "c": c, "p": p, "q": q, "value": str(K[a,c,p,q])}
            for a,c,p,q in np.ndindex(2,2,2,2) if K[a,c,p,q] != 0
        ]
    }

examples = {}
max_abs_source = 0.0
max_abs_receiver = 0.0
for ell in [2,3,4,5,8]:
    row = {"ell": ell, "mu": ell*(ell+1)}
    for name, K in Kform.items():
        Knum = eval_form(K, ell)
        row[name] = {}
        for sector in ["AA", "BB"]:
            cc = contract(Knum, sector)
            row[name][sector] = cc
            for key, mat in cc.items():
                arr = np.array(mat, dtype=float)
                if key.startswith("S_"):
                    max_abs_source = max(max_abs_source, float(np.max(np.abs(arr))))
                if key.startswith("R_"):
                    max_abs_receiver = max(max_abs_receiver, float(np.max(np.abs(arr))))
    examples[f"ell_{ell}"] = row

# Test arbitrary same-factor support separately.
def arbitrary_support_max(kind: str, chir: str, sector: str) -> float:
    maxv = 0.0
    for a,c,p,q in np.ndindex(2,2,2,2):
        H = np.zeros((4,4,4,4), dtype=float)
        if sector == "AA":
            H[a,c,p,q] = 1.0
        else:
            H[2+a,2+c,2+p,2+q] = 1.0
        mat = step96.receiver_matrix(H, chir) if kind == "R" else step96.source_matrix_over_pi2(H, chir)
        maxv = max(maxv, float(np.max(np.abs(mat))))
    return maxv

support_test = {sector: {kind+chir: arbitrary_support_max(kind, chir, sector)
                         for kind in ["R", "S"] for chir in ["plus", "minus"]}
                for sector in ["AA", "BB"]}

results = {
    "step": 99,
    "purpose": "partial normal-coordinate same-factor tensor jets omitted from Step98 restricted tensor-scalar model",
    "metric_and_J": {
        "g_O2": "delta_ij-(|x|^2 delta_ij-x_i x_j)/3",
        "J_O2_matrix": [[str(trunc(Jupdown[i,j],2)) for j in range(2)] for i in range(2)],
        "m2_scalar": "b*(x^2-y^2 or 2xy)*(1+(2-mu)r^2/12)",
    },
    "arbitrary_same_factor_support_test": support_test,
    "formula_summary": formula_summary,
    "examples": examples,
    "max_abs_receiver_on_actual_partial_jets": max_abs_receiver,
    "max_abs_source_on_actual_partial_jets": max_abs_source,
    "conclusion": [
        "Arbitrary same-factor H_ab,pq support is invisible to the Step96 receiver but not to the Step96 source functional.",
        "For the actual electric and magnetic m=2 tensor families generated on S^2, the partial same-factor tensor jets have zero source and zero receiver contraction up to symbolic/numerical precision in the tested degrees.",
        "Thus the most obvious same-factor second-derivative term omitted from Step98 does not change the H4 source/receiver pairing for these tensor modes. This supports, but does not by itself prove, completeness of the implemented tensor-scalar pair map; it still assumes the electric/magnetic tensor family and the Ozuch distributional source identification used by Step96.",
    ],
}

out = DATA_DIR / "step99_tensor_partial_jets.json"
with open(out, "w") as f:
    json.dump(results, f, indent=2)
print(json.dumps({
    "purpose": results["purpose"],
    "J_O2": results["metric_and_J"]["J_O2_matrix"],
    "arbitrary_same_factor_support_test": support_test,
    "actual_partial_jet_nonzero_counts": {k: len(v["nonzero_entries"]) for k,v in formula_summary.items()},
    "max_abs_receiver_on_actual_partial_jets": max_abs_receiver,
    "max_abs_source_on_actual_partial_jets": max_abs_source,
    "conclusion": results["conclusion"],
    "output": str(out),
}, indent=2))
