#!/usr/bin/env python3
"""
Step 94: corrected AA/BB principal adjacent response for the product-orbifold
chirality-odd Green calculation.

This repairs the Step 93 normalization defect: for the magnetic trace-free tensor
M=L_{(*df)^#}g the pole amplitude is twice the electric TF Hessian amplitude,
so ||M||^2 is four times ||E||^2.  Step 93 used the electric norm for both,
which made the separated tensor polarizations appear to reinforce instead of
cancel.

The script keeps the Step 89/91 principal normalization
    coefficient = (pi^2/2) * sum exp(-tau P) R_i(mode) R_j(mode)/(P ||mode||^2_quot)
for the sparse odd receiver R_odd.  It computes the corrected heat-regularized
AA/BB sector and records the analytic factorization showing finiteness and sign.
This is still not the full Ozuch radial coefficient: ALE H^4 source, gauge/Bianchi
projection and nonlinear gluing are separate.
"""
from __future__ import annotations

import json
import math
import pathlib
from scipy import integrate

SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
WS = SCRIPT_DIR.parent
DATA_DIR = WS / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)


def mu(l: int) -> int:
    return l * (l + 1)


def b2(l: int) -> float:
    """b_l^2 for the real m=2 scalar harmonic local form.

    In the pole frame, the L2-normalized real harmonics have Hessian amplitudes
    Hess(cos 2phi)=2b diag(1,-1), Hess(sin 2phi)=2b [[0,1],[1,0]].
    Thus (2b)^2=(2l+1) mu(mu-2)/(32*pi).
    """
    if l < 2:
        return 0.0
    m = mu(l)
    return (2 * l + 1) * m * (m - 2) / (128.0 * math.pi)


def scalar_offdiag(l: int, node: str) -> float:
    """d0d1 of the sin(m=2) scalar harmonic at N or S."""
    if l < 2:
        return 0.0
    amp = 2.0 * math.sqrt(b2(l))
    # Step 91/93 oriented south frame: sin(2phi) gains -(-1)^l.
    sign = 1.0 if node == "N" else -((-1.0) ** l)
    return sign * amp


def tensor_offdiag(l: int, kind: str, node: str) -> float:
    """Off-diagonal pole component of electric or full-Lie magnetic TF tensor.

    electric uses the sin m=2 harmonic and has amplitude 2b.
    magnetic uses the cos m=2 harmonic and the full Lie derivative L_X g, hence
    amplitude 4b.  The south-frame signs are those used in Step 93.
    """
    if l < 2:
        return 0.0
    b = math.sqrt(b2(l))
    if kind == "electric":
        sign = 1.0 if node == "N" else -((-1.0) ** l)
        return sign * 2.0 * b
    if kind == "magnetic_full_lie":
        sign = 1.0 if node == "N" else ((-1.0) ** l)
        return sign * 4.0 * b
    raise ValueError(kind)


def tf_norm(l: int, kind: str) -> float:
    """L2 norm squared on S^2 of the TF tensor generated by a unit scalar harmonic."""
    m = mu(l)
    electric_norm = 0.5 * m * (m - 2)
    if kind == "electric":
        return electric_norm
    if kind == "magnetic_full_lie":
        return 4.0 * electric_norm
    raise ValueError(kind)


def P_eigen(l_tensor: int, l_scalar: int) -> float:
    return 0.5 * (mu(l_tensor) + mu(l_scalar)) - 1.0


def aa_contribution(Lmax: int, tau: float, pair: str) -> float:
    """AA sector: tensor on A, scalar on B, receiver at NN, source at pair."""
    recA, recB = "N", "N"
    if pair == "NS":
        srcA, srcB = "N", "S"
    elif pair == "SN":
        srcA, srcB = "S", "N"
    elif pair == "SS":
        srcA, srcB = "S", "S"
    elif pair == "NN":
        srcA, srcB = "N", "N"
    else:
        raise ValueError(pair)

    total = 0.0
    for lt in range(2, Lmax + 1):
        for ls in range(2, Lmax + 1):
            P = P_eigen(lt, ls)
            heat = math.exp(-tau * P)
            d_rec = scalar_offdiag(ls, recB)
            d_src = scalar_offdiag(ls, srcB)
            if d_rec == 0.0 or d_src == 0.0:
                continue
            for kind in ["electric", "magnetic_full_lie"]:
                T_rec = tensor_offdiag(lt, kind, recA)
                T_src = tensor_offdiag(lt, kind, srcA)
                if T_rec == 0.0 or T_src == 0.0:
                    continue
                R_rec = 0.5 * d_rec * T_rec
                R_src = 0.5 * d_src * T_src
                # quotient by simultaneous antipodal halves the product norm
                norm_quot = tf_norm(lt, kind) / 2.0
                total += (math.pi ** 2 / 2.0) * heat * R_rec * R_src / (P * norm_quot)
    return total


def bb_contribution(Lmax: int, tau: float, pair: str) -> float:
    """BB sector: tensor on B, scalar on A, receiver at NN, source at pair."""
    recA, recB = "N", "N"
    if pair == "NS":
        srcA, srcB = "N", "S"
    elif pair == "SN":
        srcA, srcB = "S", "N"
    elif pair == "SS":
        srcA, srcB = "S", "S"
    elif pair == "NN":
        srcA, srcB = "N", "N"
    else:
        raise ValueError(pair)

    total = 0.0
    for lt in range(2, Lmax + 1):  # tensor degree on B
        for ls in range(2, Lmax + 1):  # scalar degree on A
            P = P_eigen(lt, ls)
            heat = math.exp(-tau * P)
            d_rec = scalar_offdiag(ls, recA)
            d_src = scalar_offdiag(ls, srcA)
            if d_rec == 0.0 or d_src == 0.0:
                continue
            for kind in ["electric", "magnetic_full_lie"]:
                T_rec = tensor_offdiag(lt, kind, recB)
                T_src = tensor_offdiag(lt, kind, srcB)
                if T_rec == 0.0 or T_src == 0.0:
                    continue
                R_rec = 0.5 * d_rec * T_rec
                R_src = 0.5 * d_src * T_src
                norm_quot = tf_norm(lt, kind) / 2.0
                total += (math.pi ** 2 / 2.0) * heat * R_rec * R_src / (P * norm_quot)
    return total


def pair_response(Lmax: int, tau: float, pair: str) -> dict:
    aa = aa_contribution(Lmax, tau, pair)
    bb = bb_contribution(Lmax, tau, pair)
    return {"pair": pair, "Lmax": Lmax, "tau": tau, "K_AA_corrected": aa, "K_BB_corrected": bb, "K_AABB_corrected": aa + bb}


def direct_ladder() -> list[dict]:
    ladder = []
    for tau, L in [(0.1, 80), (0.05, 120), (0.02, 180), (0.01, 260), (0.005, 380), (0.003, 520)]:
        row = {"tau": tau, "Lmax": L}
        for pair in ["NS", "SN", "SS"]:
            resp = pair_response(L, tau, pair)
            row[pair] = {k: resp[k] for k in ["K_AA_corrected", "K_BB_corrected", "K_AABB_corrected"]}
        ladder.append(row)
    return ladder


def analytic_polarization_checks() -> dict:
    checks = []
    for l in range(2, 8):
        Ne = tf_norm(l, "electric")
        Nm = tf_norm(l, "magnetic_full_lie")
        e_same = tensor_offdiag(l, "electric", "N") * tensor_offdiag(l, "electric", "N") / Ne
        m_same = tensor_offdiag(l, "magnetic_full_lie", "N") * tensor_offdiag(l, "magnetic_full_lie", "N") / Nm
        e_sep = tensor_offdiag(l, "electric", "N") * tensor_offdiag(l, "electric", "S") / Ne
        m_sep = tensor_offdiag(l, "magnetic_full_lie", "N") * tensor_offdiag(l, "magnetic_full_lie", "S") / Nm
        checks.append({
            "ell": l,
            "electric_norm": Ne,
            "magnetic_full_lie_norm": Nm,
            "same_pole_electric_normalized": e_same,
            "same_pole_magnetic_normalized": m_same,
            "same_pole_sum": e_same + m_same,
            "separated_electric_normalized": e_sep,
            "separated_magnetic_normalized": m_sep,
            "separated_sum": e_sep + m_sep,
        })
    return {
        "statement": "same-pole tensor polarizations reinforce equally; antipodal tensor polarizations cancel exactly after correcting magnetic norm",
        "checks": checks,
    }


def heat_series_A(s: float, Lmax: int = 4000) -> float:
    """A0(s)=sum_{l>=2}(2l+1) exp(-s mu/2)."""
    total = 0.0
    for l in range(2, Lmax + 1):
        total += (2 * l + 1) * math.exp(-0.5 * s * mu(l))
    return total


def heat_series_B2_alt(s: float, Lmax: int = 4000) -> float:
    """B2(s)=sum_{l>=2}(-1)^l(2l+1)mu(mu-2) exp(-s mu/2)."""
    total = 0.0
    for l in range(2, Lmax + 1):
        m = mu(l)
        total += ((-1) ** l) * (2 * l + 1) * m * (m - 2) * math.exp(-0.5 * s * m)
    return total


def integrand_AA_NS(s: float) -> float:
    # K_AA_NS = -1/1024 int_0^inf e^s A0(s) B2_alt(s) ds.
    if s < 1e-5:
        # antipodal second derivative gives exponential suppression; returning 0
        # avoids roundoff from alternating finite sums near zero.
        return 0.0
    L = min(5000, max(200, int(30.0 / math.sqrt(s))))
    return math.exp(s) * heat_series_A(s, L) * heat_series_B2_alt(s, L)


def numerical_integral_formula() -> dict:
    intervals = [(1e-4, 20), (1e-3, 20), (1e-2, 20), (1e-4, 50)]
    vals = []
    for lo, hi in intervals:
        val, err = integrate.quad(integrand_AA_NS, lo, hi, limit=200, epsabs=1e-8, epsrel=1e-7)
        vals.append({"lower": lo, "upper": hi, "raw_integral": val, "quad_error": err, "K_AA_NS_formula": -val / 1024.0})
    return {
        "formula": "K_AA_NS = -1/1024 int_0^infty e^s A0(s) B2(s) ds",
        "A0": "sum_{ell>=2}(2ell+1) exp[-s mu_ell/2] > 0",
        "B2": "sum_{ell>=2}(-1)^ell(2ell+1)mu_ell(mu_ell-2) exp[-s mu_ell/2] = 32*pi d_x^2 p_{s/2}^{S2}(-1)",
        "sign_if_dimension_raising_applies": "d_x^2 p_t^{S2}(-1)=4*pi^2 e^{-6t} p_t^{S6}(-1)>0, hence K_AA_NS<0",
        "quadrature": vals,
    }


