def canonical_pm(v):
    """Canonical representative of the unoriented circle generated by primitive v."""
    a, b = v
    # reduce just in case
    g = math.gcd(abs(a), abs(b)) or 1
    a, b = a // g, b // g
    if a < 0 or (a == 0 and b < 0):
        a, b = -a, -b
    return (a, b)


def det(u, v):
    return u[0] * v[1] - u[1] * v[0]


def fan_audit(name, labels, known_status, source):
    classes = defaultdict(list)
    for i, v in enumerate(labels):
        classes[canonical_pm(v)].append(i + 1)
    adj = []
    for i in range(len(labels)):
        adj.append(det(labels[i], labels[(i + 1) % len(labels)]))
    same = {str(k): inds for k, inds in classes.items() if len(inds) > 1}
    return {
        "name": name,
        "labels_cyclic": labels,
        "m_edges": len(labels),
        "adjacent_determinants": adj,
        "delzant_abs_det_all_one": all(abs(x) == 1 for x in adj),
        "same_unoriented_circle_classes": same,
        "max_same_circle_count": max(len(v) for v in classes.values()),
        "known_status": known_status,
        "source": source,
    }


def page_poly(nu):
    return nu**4 + 4 * nu**3 - 6 * nu**2 + 12 * nu - 3


def page_metric_calibration():
    """Compute Page orbit-base K integral and primitive-slope equalities.

    Formula from Toric-U(2)-and-LeBrun-metrics lines 319--340:
      g = S[A(r)dr^2 + B(r)(dpsi+cos(theta)dphi)^2
             + C(r)(dtheta^2+sin^2(theta)dphi^2)]
    for the T^2 generated by psi,phi.  The orbit base is
      g_B = S[A(r)dr^2 + C(r)dtheta^2].
    """
    nu = brentq(page_poly, 0.0, 1.0)
    Lambda = 1.0
    S = 3 * (1 + nu**2) / Lambda
    D0 = 3 + 6 * nu**2 - nu**4

    r = sp.symbols("r")
    nu_s = sp.Float(nu, 50)
    S_s = sp.Float(S, 50)
    D0_s = sp.Float(D0, 50)
    c2 = sp.cos(r) ** 2
    A = (1 - nu_s * c2) / (3 - nu_s**2 - nu_s**2 * (1 + nu_s**2) * c2)
    B = ((3 - nu_s**2 - nu_s**2 * (1 + nu_s**2) * c2) /
         ((3 + nu_s**2) ** 2 * (1 - nu_s * c2)) * sp.sin(r) ** 2)
    C = 4 * (1 - nu_s**2 * c2) / D0_s
    E = S_s * A
    G = S_s * C
    sqrtG = sp.sqrt(G)
    # K=-1/sqrt(EG) d/dr[(d sqrt(G)/dr)/sqrt(E)]
    K_expr = -sp.diff(sp.diff(sqrtG, r) / sp.sqrt(E), r) / sp.sqrt(E * G)
    area_expr = sp.sqrt(E * G)
    K_func = sp.lambdify(r, K_expr, "numpy")
    area_func = sp.lambdify(r, area_expr, "numpy")
    B_func = sp.lambdify(r, B, "numpy")
    A_func = sp.lambdify(r, A, "numpy")
    C_func = sp.lambdify(r, C, "numpy")

    # Base integral.  theta runs over [0,pi].
    def integrand_K(x):
        return float(K_func(x) * area_func(x))
    intK = math.pi * quad(integrand_K, 0.0, math.pi, points=[0.0, math.pi], epsabs=1e-10, epsrel=1e-10, limit=300)[0]

    # Curvature statistics avoiding endpoints.
    xs = np.linspace(1e-5, math.pi - 1e-5, 2001)
    Ks = np.array([float(K_func(x)) for x in xs])

    # r-edge slope for collapsing vector d/dpsi at r=0 and r=pi.
    # norm^2 = S B(r); base distance^2 = S A(r0) dr^2, so slope^2=B2/A0.
    # In fact, with D=3-2nu^2-nu^4=(1-nu^2)(3+nu^2), the limiting slope is
    # D/((3+nu^2)(1-nu)) = 1+nu at both ends.  We also compute numerical
    # small-r fits as a sanity check.
    eps_values = [1e-4, 5e-5, 2e-5, 1e-5]
    r0_slopes = []
    rpi_slopes = []
    for eps in eps_values:
        r0_slopes.append(math.sqrt(max(float(B_func(eps)), 0.0) / (float(A_func(0.0)) * eps**2)))
        rpi_slopes.append(math.sqrt(max(float(B_func(math.pi - eps)), 0.0) / (float(A_func(math.pi)) * eps**2)))
    kappa_r0 = r0_slopes[-1]
    kappa_rpi = rpi_slopes[-1]

    # theta-edge slope for collapsing vector d/dpsi-d/dphi at theta=0, and
    # d/dpsi+d/dphi at theta=pi.  For either edge, norm^2 ~ S C(r) theta^2
    # and base distance^2 ~ S C(r) dtheta^2, hence slope = 1 identically.
    theta_slope_samples = []
    for frac in [0.05, 0.25, 0.5, 0.75, 0.95]:
        rr = frac * math.pi
        theta_slope_samples.append({
            "r/pi": frac,
            "theta0_label_(1,-1)_slope_formula": 1.0,
            "thetapi_label_(1,1)_slope_formula": 1.0,
            "C(r)": float(C_func(rr)),
        })

    # Exact-ish labels in the (psi,phi) basis around the rectangle.  Depending
    # on orientation/cyclic start, this is a GL(2,Z)-equivalent F1 fan.
    page_labels_u2_basis = [(1, 0), (1, -1), (1, 0), (1, 1)]

    return {
        "nu_root": nu,
        "source_formula": "Knowledge/objects/papers/Toric-U-2-and-LeBrun-metrics--fb99f416c130--13e07193d27a/object.md lines 319-340",
        "orbit_base": "g_B=S[A(r)dr^2+C(r)dtheta^2], theta in [0,pi]",
        "labels_in_U2_basis": page_labels_u2_basis,
        "same_circle_class": {"(1,0)": [1, 3]},
        "base_gauss_bonnet": {
            "m": 4,
            "right_angle_prediction_intK": 0.0,
            "computed_intK": intK,
            "abs_error": abs(intK),
            "interpretation": "Page reproduces ∫K_B=0 for a right-angled quadrilateral while K_B is not identically zero.",
        },
        "K_B_stats": {
            "min": float(np.min(Ks)),
            "max": float(np.max(Ks)),
            "not_identically_zero": bool(np.max(np.abs(Ks)) > 1e-3),
            "sample_values": [
                {"r/pi": frac, "K_B": float(K_func(frac * math.pi))}
                for frac in [0.05, 0.25, 0.5, 0.75, 0.95]
            ],
        },
        "slope_checks": {
            "r_edges_collapsing_(1,0)": {
                "kappa_exact_in_U2_basis": 1.0 + nu,
                "kappa_r0_last": kappa_r0,
                "kappa_rpi_last": kappa_rpi,
                "error_r0_vs_exact": abs(kappa_r0 - (1.0 + nu)),
                "error_rpi_vs_exact": abs(kappa_rpi - (1.0 + nu)),
                "relative_difference": abs(kappa_r0 - kappa_rpi) / max(abs(kappa_r0), 1e-300),
                "eps_sequence": eps_values,
                "kappa_r0_sequence": r0_slopes,
                "kappa_rpi_sequence": rpi_slopes,
                "note": "Equality of the two same-circle r-edge slopes is the meaningful calibration here; unit value depends on Euler-angle/primitive-period convention. The common U(2)-basis value is exactly 1+nu from the Page formula.",
            },
            "theta_edges": theta_slope_samples,
        },
    }


