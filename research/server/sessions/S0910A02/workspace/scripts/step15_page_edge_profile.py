"""
Step 15: Page metric orbit-base curvature/rod profile probe.

Uses the explicit Page metric formula from Knowledge/objects/papers/
Toric-U-2-and-LeBrun-metrics--... lines 319--340:

 g = S[ A(r)dr^2 + B(r)(dpsi+cos(theta)dphi)^2
        + C(r)(dtheta^2+sin^2(theta)dphi^2) ],
 S=3(1+nu^2)/Lambda.

For the T^2 generated by psi,phi, the quotient metric is
    g_B = S[A(r)dr^2 + C(r)dtheta^2]
and det(h)=S^2 B(r)C(r)sin^2 theta.  We compute Gaussian curvature K_B(r),
edge values on the four polygon sides, and the rod-flux identity diagnostics.

Caveat: Euler-angle periods/lattice normalizations in the Page U(2) chart can
change flux by integer factors.  K_B profiles are period-independent; flux
checks are recorded as normalization diagnostics, not as final source-grade
per-sphere GB verification.
"""
import json, math, os
import numpy as np
from scipy.integrate import quad
from scipy.optimize import brentq

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.abspath(os.path.join(HERE, "..", "data"))
os.makedirs(DATA, exist_ok=True)

# Known Page parameter: root in (0,1) of nu^4 + 4nu^3 - 6nu^2 + 12nu - 3 = 0.
def page_poly(nu):
    return nu**4 + 4*nu**3 - 6*nu**2 + 12*nu - 3

nu = brentq(page_poly, 0.0, 1.0)
Lambda = 1.0
S = 3*(1+nu**2)/Lambda
D0 = 3 + 6*nu**2 - nu**4


def A0(r):
    c2 = math.cos(r)**2
    return (1 - nu*c2)/(3 - nu**2 - nu**2*(1+nu**2)*c2)

def B0(r):
    c2 = math.cos(r)**2
    return ((3 - nu**2 - nu**2*(1+nu**2)*c2) /
            ((3+nu**2)**2*(1 - nu*c2)) * math.sin(r)**2)

def C0(r):
    c2 = math.cos(r)**2
    return 4*(1 - nu**2*c2)/D0

def E(r):
    return S*A0(r)

def G(r):
    return S*C0(r)

def hB(r):
    return S*B0(r)

def hC(r):
    return S*C0(r)

# Gaussian curvature for ds^2=E(r)dr^2+G(r)dtheta^2.
# K=-1/sqrt(G) * (1/sqrt(E)) d/dr[(d sqrt(G)/dr)/sqrt(E)].
def deriv(f, r, h=1e-5):
    # avoid endpoints with one-sided finite difference
    if r-h <= 0:
        return (-3*f(r)+4*f(r+h)-f(r+2*h))/(2*h)
    if r+h >= math.pi:
        return (3*f(r)-4*f(r-h)+f(r-2*h))/(2*h)
    return (f(r+h)-f(r-h))/(2*h)

def K_base(r):
    def sqrtG(x): return math.sqrt(G(x))
    def inner(x): return deriv(sqrtG, x)/math.sqrt(E(x))
    return - deriv(inner, r)/math.sqrt(G(r))

# More stable samples using moderate endpoint offsets.
rs = np.linspace(1e-4, math.pi-1e-4, 501)
Ks = np.array([K_base(float(r)) for r in rs])

# Edge diagnostics.  Four edges: theta=0, theta=pi, r=0, r=pi.
# Along theta edges: ds=sqrt(E)dr, noncollapsed circle coefficient q=sqrt(hB).
def flux_theta_edge():
    f_flux = lambda r: math.sqrt(max(hB(r),0.0))*math.sqrt(E(r))
    f_gb = lambda r: (1 - 2*K_base(r))*f_flux(r)
    flux = quad(f_flux, 0, math.pi, points=[0, math.pi], limit=200)[0]
    gb_half = quad(f_gb, 0, math.pi, points=[0, math.pi], limit=200)[0]
    return flux, gb_half

# Along r endpoint edges: ds=sqrt(G(r0))dtheta, q=sqrt(hC(r0))*sin(theta).
def flux_r_edge(r0):
    K0 = K_base(1e-5 if r0 == 0 else math.pi-1e-5)
    # C is constant along theta at fixed r0.
    Cval = hC(r0)
    flux = Cval * 2.0  # integral_0^pi sin theta dtheta times sqrtC*sqrtC
    gb_half = (1 - 2*K0)*flux
    return flux, gb_half, K0

flux_th, gb_th = flux_theta_edge()
flux_r0, gb_r0, K_r0 = flux_r_edge(0.0)
flux_rpi, gb_rpi, K_rpi = flux_r_edge(math.pi)

# Total volume through orbit formula with 2pi-period convention.
def int_w():
    integrand_r = lambda r: math.sqrt(max(hB(r)*hC(r),0.0))*math.sqrt(E(r)*G(r))
    # integrate theta sin theta =2
    return 2.0 * quad(integrand_r, 0, math.pi, points=[0, math.pi], limit=200)[0]
Iw = int_w()
Vol_2pi = 4*math.pi**2*Iw

# Basic curvature profile stats
profile_samples = []
for frac in [0.0,0.1,0.25,0.5,0.75,0.9,1.0]:
    r = min(max(frac*math.pi, 1e-5), math.pi-1e-5)
    profile_samples.append({"r/pi": frac, "K_B": K_base(r), "B": hB(r), "C": hC(r)})

report = {
    "title": "Step 15 Page metric edge K_B profile from explicit U(2) formula",
    "source": "Toric-U-2-and-LeBrun-metrics object.md lines 319-340; Page parameter root of nu^4+4nu^3-6nu^2+12nu-3=0",
    "nu": nu,
    "Lambda_used": Lambda,
    "scale_S": S,
    "base_metric": "g_B=S[A(r)dr^2+C(r)dtheta^2]",
    "K_B_profile_stats": {
        "min": float(np.min(Ks)), "max": float(np.max(Ks)),
        "mean_sample": float(np.mean(Ks)),
        "samples": profile_samples,
        "interpretation": "K_B varies mildly and changes sign (about -0.095 to 0.075 in this normalization/profile); Page is not a large negative edge-bubble model."
    },
    "edge_flux_diagnostics_2pi_lattice_convention": {
        "theta=0_edge": {"flux": flux_th, "integral_(1-2K)qds": gb_th},
        "theta=pi_edge": {"flux": flux_th, "integral_(1-2K)qds": gb_th},
        "r=0_edge": {"flux": flux_r0, "integral_(1-2K)qds": gb_r0, "K_edge": K_r0},
        "r=pi_edge": {"flux": flux_rpi, "integral_(1-2K)qds": gb_rpi, "K_edge": K_rpi},
        "expected_if_primitive_period_2pi": "For the twist-free primitive rod convention one expects integral_(1-2K)qds=2 per edge. Deviations here are likely lattice/Euler-angle normalization and/or using the U(2) chart without converting to primitive toric coordinates.",
    },
    "orbit_integral_diagnostic": {"int_w_2pi_convention": Iw, "Vol4_2pi_convention": Vol_2pi},
    "use_for_step15": [
        "This partially completes target C for Page: it gives an explicit K_B edge/profile diagnostic from a source formula.",
        "It does not yield a CLW profile; Hall-Murphy says CLW is cohomogeneity two and nonconstructive, so computing CLW edge K_B requires separate numerical extremal-Kahler data/code.",
        "Page has m=4 and no boundary-bubble signature; it is a calibration example, not evidence about large-chi collapse."
    ]
}
OUT=os.path.join(DATA,"step15_page_edge_profile.json")
with open(OUT,"w") as f:
    json.dump(report,f,indent=2)
print(json.dumps({
    "nu":nu,
    "K_stats": report["K_B_profile_stats"],
    "edge_flux_diagnostics": report["edge_flux_diagnostics_2pi_lattice_convention"],
    "Vol4_2pi_convention": Vol_2pi,
    "saved": OUT,
},indent=2))
