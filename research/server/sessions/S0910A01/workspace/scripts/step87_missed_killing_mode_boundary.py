#!/usr/bin/env python3
"""
Step 87: exact boundary-pairing calculation for the missed invariant
Killing-one-form product mode on (S^2 x S^2)/Z_2.

The Strategist correction to Step 86 points out that product eigentensors do
not force tensor indices to equal the quadratic-jet derivative indices.  The
mode
    alpha=*du_A, beta=*du_B, h=alpha⊗beta+beta⊗alpha
for height functions u_A,u_B is a mixed product eigentensor with P h = h.
Near NN, in coordinates x0,x1 on A and x2,x3 on B,
    alpha = x1 dx0 - x0 dx1 + O(r_A^3),
    beta  = x3 dx2 - x2 dx3 + O(r_B^3).
This script computes the Ozuch-style boundary source projection
    B_eps(V2)=3 ∫_{S^3/Z2} <H^4_eps, V2> dσ
for this mode and for the four linear-linear AB modes generated by du_z and
*du_z on each factor.  It also reports the bilinear defect contraction
D_{ij,mn} M_{ij,mn}, showing explicitly why Step 86's diagonal D_{ij,ij}
restriction missed this eigentensor.

The output is a boundary/source projection computation only.  It is not the
full receiving radial coefficient L_i G_P^⊥ S_j; the receiver functional and
node transport remain separate analytic identifications.
"""
import json, math, os
from fractions import Fraction
import numpy as np


def wedge(i, j, n=4):
    A = np.zeros((n, n), dtype=int)
    A[i, j] = 1
    A[j, i] = -1
    return A


def build_C():
    e01 = wedge(0, 1); e02 = wedge(0, 2); e03 = wedge(0, 3)
    e12 = wedge(1, 2); e13 = wedge(1, 3); e23 = wedge(2, 3)
    # Use the same convention as Steps 84-86.  Although wp,wm have 1/sqrt(2),
    # the symmetrized products have integral entries.
    rt2 = math.sqrt(2.0)
    wp = [(e01 + e23)/rt2, (e02 - e13)/rt2, (e03 + e12)/rt2]
    wm = [(e01 - e23)/rt2, (e02 + e13)/rt2, (e03 - e12)/rt2]
    C = np.zeros((3, 3, 4, 4))
    for a in range(3):
        for b in range(3):
            prod = wp[a] @ wm[b]
            C[a, b] = prod + prod.T
    # Round to exact integers for rational moment calculation.
    C_int = np.rint(C).astype(int)
    if np.max(np.abs(C - C_int)) > 1e-12:
        raise RuntimeError("C matrices were not integral in this convention")
    return C_int


def moment_coeff(a, b, p, q):
    """Return coefficient c with ∫_{S^3} x_a x_b x_p x_q dσ = c*pi^2."""
    return Fraction((1 if a == b and p == q else 0) +
                    (1 if a == p and b == q else 0) +
                    (1 if a == q and b == p else 0), 12)


def oneform_linear(kind, factor):
    """Linear leading coefficient A[i,p] so one-form component alpha_i=sum_p A[i,p] x_p.

    kind='grad' gives du_z = -x0 dx0 - x1 dx1 on A, and analogously on B.
    kind='kill' gives *du_z = x1 dx0 - x0 dx1 on A, and analogously on B.
    """
    A = np.zeros((4, 4), dtype=int)
    if factor == 'A':
        i0, i1 = 0, 1
    elif factor == 'B':
        i0, i1 = 2, 3
    else:
        raise ValueError(factor)
    if kind == 'grad':
        A[i0, i0] = -1
        A[i1, i1] = -1
    elif kind == 'kill':
        # x_{i1} dx_{i0} - x_{i0} dx_{i1}
        A[i0, i1] = 1
        A[i1, i0] = -1
    else:
        raise ValueError(kind)
    return A


def sym_product_quadratic(A, B):
    """Return M[i,j,p,q] for V_ij(x)=sum_{p,q} M_ijpq x_p x_q,
    where V=alpha⊗beta+beta⊗alpha and alpha_i=A[i,p]x_p, beta_j=B[j,q]x_q.
    """
    M = np.zeros((4, 4, 4, 4), dtype=int)
    for i in range(4):
        for j in range(4):
            for p in range(4):
                for q in range(4):
                    M[i, j, p, q] += A[i, p] * B[j, q] + B[i, p] * A[j, q]
    return M


def boundary_pairing_pi2_coeff(C, M, chirality):
    """Exact rational K such that 3∫_{S^3/Z2}<H^4_chirality,V2>dσ = K*pi^2.

    H^4_+ = -1/2 sum_k (x^T C[1,k] x) C[1,k]
    H^4_- = -1/2 sum_k (x^T C[k,1] x) C[k,1]
    Integral over RP^3 is half the integral over S^3.
    """
    total = Fraction(0, 1)
    for k in range(3):
        A = C[1, k] if chirality == '+' else C[k, 1]
        for a in range(4):
            for b in range(4):
                Aab = int(A[a, b])
                if Aab == 0:
                    continue
                for i in range(4):
                    for j in range(4):
                        Aij = int(A[i, j])
                        if Aij == 0:
                            continue
                        for p in range(4):
                            for q in range(4):
                                coeff = int(M[i, j, p, q])
                                if coeff:
                                    total += Fraction(Aab * Aij * coeff, 1) * moment_coeff(a, b, p, q)
    # H factor -1/2; quotient integral 1/2; Ozuch factor 3.
    return Fraction(-3, 4) * total


def bilinear_defect(C):
    D = np.zeros((4, 4, 4, 4), dtype=int)
    for i in range(4):
        for j in range(4):
            for m in range(4):
                for n in range(4):
                    D[i, j, m, n] = sum(int(C[1, k, i, j]) * int(C[1, k, m, n]) -
                                        int(C[k, 1, i, j]) * int(C[k, 1, m, n])
                                        for k in range(3))
    return D


def defect_contraction(D, M):
    # This is sum D_{ij,pq} M_{ij,pq}; proportional to the chirality difference.
    return int(np.einsum('ijpq,ijpq->', D, M))


def nonzero_terms(M):
    out = []
    for i in range(4):
        for j in range(4):
            for p in range(4):
                for q in range(4):
                    c = int(M[i, j, p, q])
                    if c:
                        out.append([i, j, p, q, c])
    return out


def mode_report(C, D, name, A_kind, B_kind):
    A = oneform_linear(A_kind, 'A')
    B = oneform_linear(B_kind, 'B')
    M = sym_product_quadratic(A, B)
    bp = boundary_pairing_pi2_coeff(C, M, '+')
    bm = boundary_pairing_pi2_coeff(C, M, '-')
    diff = bp - bm
    dcontr = defect_contraction(D, M)
    # Relation: B_+ - B_- = (-3/4)*(pi^2/12)*sum D*M?  Need not state as theorem;
    # include both exact computations for consistency.
    return {
        'name': name,
        'A_oneform': A_kind,
        'B_oneform': B_kind,
        'source_projection_plus_over_pi2': f'{bp.numerator}/{bp.denominator}',
        'source_projection_minus_over_pi2': f'{bm.numerator}/{bm.denominator}',
        'source_projection_difference_plus_minus_over_pi2': f'{diff.numerator}/{diff.denominator}',
        'float_plus': float(bp),
        'float_minus': float(bm),
        'float_difference': float(diff),
        'D_contraction_sum_Dijpq_Mijpq': dcontr,
        'nonzero_quadratic_jet_terms': nonzero_terms(M),
    }


def transform_matrix_A():
    # Simultaneous antipodal on tangent link acts by -I on all four local coords.
    return -np.eye(4, dtype=int)


def transform_matrix_J():
    # Simultaneous conjugation J(z,w)=(zbar,wbar): (x0,x1,x2,x3)->(x0,-x1,x2,-x3)
    return np.diag([1, -1, 1, -1]).astype(int)


def transform_mode(M, R):
    """Passive check of V2 invariance under orthogonal map R on coords/tensors:
    (R^* V)_{ij}(x)=R_{a i} R_{b j} V_{ab}(R x).  For polynomial coeffs.
    """
    # V_ab(Rx) has coeff M[a,b,p,q] R[p,r] R[q,s] x_r x_s.
    # Pullback tensor components multiply R[a,i]R[b,j].
    Mt = np.zeros_like(M)
    for i in range(4):
        for j in range(4):
            for r in range(4):
                for s in range(4):
                    val = 0
                    for a in range(4):
                        for b in range(4):
                            Ra_i = int(R[a, i]); Rb_j = int(R[b, j])
                            if Ra_i == 0 or Rb_j == 0:
                                continue
                            for p in range(4):
                                for q in range(4):
                                    coeff = int(M[a, b, p, q])
                                    if coeff:
                                        val += Ra_i * Rb_j * coeff * int(R[p, r]) * int(R[q, s])
                    Mt[i, j, r, s] = val
    return Mt


def main():
    C = build_C()
    D = bilinear_defect(C)
    reports = []
    for Ak in ['grad', 'kill']:
        for Bk in ['grad', 'kill']:
            reports.append(mode_report(C, D, f'{Ak}A_{Bk}B', Ak, Bk))

    # Detailed invariance check for the Strategist's missed Killing-Killing mode.
    A = oneform_linear('kill', 'A')
    B = oneform_linear('kill', 'B')
    M = sym_product_quadratic(A, B)
    MA = transform_mode(M, transform_matrix_A())
    MJ = transform_mode(M, transform_matrix_J())

    # Extract the exact entries mentioned by the Strategist.
    key_entries = {
        'h_03_x1_x2_coeff': int(M[0, 3, 1, 2]),
        'h_12_x0_x3_coeff': int(M[1, 2, 0, 3]),
        'D_03_12': int(D[0, 3, 1, 2]),
        'D_12_03': int(D[1, 2, 0, 3]),
        'D_30_12': int(D[3, 0, 1, 2]),
        'D_21_03': int(D[2, 1, 0, 3]),
    }

    results = {
        'scope': 'exact source boundary projection for missed linear-linear AB eigentensors at NN',
        'normalization': 'B_eps(V2)=3*int_{S^3/Z2}<H^4_eps,V2>dσ; reported as rational multiples of pi^2; V=alpha⊗beta+beta⊗alpha without 1/2 symmetrization',
        'C_convention': 'same SD/ASD C_ab convention as Steps 84-86, 0-based indices with C[1,k]=C_{2,k+1}',
        'strategist_missed_mode': 'killA_killB, alpha=x1 dx0-x0 dx1, beta=x3 dx2-x2 dx3',
        'eigenvalue_of_mixed_oneform_sector': 'P h = h in Step85 ledger: 0.5*(2+2-2)=1',
        'mode_reports': reports,
        'killing_killing_key_entries': key_entries,
        'killing_killing_invariance': {
            'A_simultaneous_antipodal_max_abs_pullback_minus_original': int(np.max(np.abs(MA - M))),
            'J_simultaneous_conjugation_max_abs_pullback_minus_original': int(np.max(np.abs(MJ - M))),
        },
        'important_interpretation': [
            'The missed invariant mode has nonzero plus-minus source projection difference; Step86 only tested diagonal D_{ij,ij}-type contractions and therefore skipped this channel.',
            'This source projection is a real nonzero input to the orthogonal-complement Green response, but it is not by itself the full radial coefficient L_i G_P^perp S_j.',
            'For this mode V0=0 at every pole, so the boundary projection uses the quadratic jet without the receiver constant-jet/frame correction that affects modes with nonzero constant term.'
        ]
    }
    outpath = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'data', 'step87_missed_killing_mode_boundary.json')
    os.makedirs(os.path.dirname(outpath), exist_ok=True)
    with open(outpath, 'w') as f:
        json.dump(results, f, indent=2)
    print(json.dumps(results, indent=2))
    print(f'Wrote {outpath}')


if __name__ == '__main__':
    main()
