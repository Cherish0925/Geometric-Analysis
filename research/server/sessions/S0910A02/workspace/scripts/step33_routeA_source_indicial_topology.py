def fetch(url: str, max_bytes: int = 3_000_000) -> Dict[str, Any]:
    req = urllib.request.Request(url, headers={"User-Agent": "Qiushi-Yau26-Step33/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            data = r.read(max_bytes)
            return {
                "ok": True,
                "url": url,
                "final_url": getattr(r, "url", url),
                "status": getattr(r, "status", None),
                "content_type": r.headers.get("Content-Type", ""),
                "bytes": len(data),
                "data_text": data.decode("utf-8", errors="replace"),
                "starts_pdf": data.startswith(b"%PDF"),
            }
    except Exception as e:
        return {"ok": False, "url": url, "error": repr(e), "data_text": "", "bytes": 0, "starts_pdf": False}


def html_to_text(s: str) -> str:
    # Crude but robust for arxiv HTML generated by LaTeXML.  Keep theorem labels/readable math words.
    s = re.sub(r"(?is)<script.*?</script>|<style.*?</style>", " ", s)
    s = re.sub(r"(?is)<(p|div|section|article|h[1-6]|li|br|tr|td|th)[^>]*>", "\n", s)
    s = re.sub(r"(?is)<[^>]+>", " ", s)
    s = unescape(s)
    s = re.sub(r"[ \t\r\f\v]+", " ", s)
    s = re.sub(r"\n\s+", "\n", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


def snippets(text: str, patterns: List[str], window: int = 900, max_each: int = 8) -> List[Dict[str, str]]:
    hits = []
    for pat in patterns:
        count = 0
        for m in re.finditer(pat, text, flags=re.IGNORECASE):
            a = max(0, m.start() - window)
            b = min(len(text), m.end() + window)
            hits.append({"pattern": pat, "start": m.start(), "snippet": text[a:b]})
            count += 1
            if count >= max_each:
                break
    # De-duplicate overlapping snippets crudely by start.
    seen = set(); out=[]
    for h in sorted(hits, key=lambda x: x["start"]):
        key = h["start"] // 500
        if key not in seen:
            seen.add(key); out.append(h)
    return out[:30]


