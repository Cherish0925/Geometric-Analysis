"""Evaluate the Step-96 relative horizontal charge-work diagnostic R_X.

The metric samples are generated by the full s-dependent charged Koiso Einstein
Cauchy evolution. For a compactly supported quotient vector field X=chi(n)d_n,
compute
  numerator = |1/2 int q_charge^T K_X q_charge dmu_sigma|
and the invariant-norm denominator proposed by the Strategist. In the fixed-charge
continuum germ the numerator vanishes already by algebraic integration by parts:
(1/2)c^T K_X c=div_sigma(QX). This computation is therefore a null control for
the K_X implementation and numerical charge conservation, not an independent
Noether test.

Only short intervals for which constraint errors converge spectrally are used.
"""
from pathlib import Path
import json, math, importlib.util
import numpy as np
from scipy.integrate import solve_ivp

p=Path('workspace/scripts/step96_koiso_einstein_cauchy_evolution.py')
spec=importlib.util.spec_from_file_location('evol',p);ev=importlib.util.module_from_spec(spec);spec.loader.exec_module(ev)


def cutoff(n,L):
    # sin^4(pi n/L): compactly supported after zero extension, with enough
    # endpoint vanishing for the integration-by-parts identity.
    return math.sin(math.pi*n/L)**4

def cutoff_prime(n,L):
    x=math.pi*n/L
    return 4*(math.pi/L)*math.sin(x)**3*math.cos(x)


def sample_fields(y,N):
    q,k=ev.unpack_symmetric(y,N)
    qi=np.linalg.inv(q)
    _,ric,_=ev.christoffel_and_ricci(q)
    W=np.einsum('nij,njk->nik',qi,k); H=np.trace(W,axis1=1,axis2=2)
    kqik=np.einsum('nij,njk,nkl->nil',k,qi,k)
    kn=ric+3*q-H[:,None,None]*k+2*kqik
    qn=2*k; qnn=2*kn
    G=q[:,1:,1:];Gi=np.linalg.inv(G);v=q[:,1:,0]
    Gn=qn[:,1:,1:];vn=qn[:,1:,0]
    Gnn=qnn[:,1:,1:];vnn=qnn[:,1:,0]
    a2=q[:,0,0]-np.einsum('ni,nij,nj->n',v,Gi,v)
    a=np.sqrt(a2)
    # derivative a_n from a2_n, now allowing v !=0
    Gin=-np.einsum('nij,njk,nkl->nil',Gi,Gn,Gi)
    a2n=qn[:,0,0]-2*np.einsum('ni,nij,nj->n',vn,Gi,v)-np.einsum('ni,nij,nj->n',v,Gin,v)
    an=.5*a2n/a
    A=np.einsum('nij,nj->ni',Gi,v)
    An=np.einsum('nij,nj->ni',Gi,vn-np.einsum('nij,nj->ni',Gn,A))
    # Orthonormal base curvature coefficient f=A_n/a and charge c=rho G f.
    f=An/a[:,None]
    rho=np.sqrt(np.linalg.det(G)); sigma=np.log(rho)
    charge=rho[:,None]*np.einsum('nij,nj->ni',G,f)
    Q=.5*np.einsum('ni,nij,nj->n',f,G,f)
    sigman=.5*np.einsum('nij,nji->n',Gi,Gn)
    # A_mat=e^-3sigma M^-1 = rho^-2 G^-1.
    Amat=Gi/(rho[:,None,None]**2)
    Amatn=Gin/(rho[:,None,None]**2)-2*sigman[:,None,None]*Amat
    # Shape-map normal speed squared: M^-1 M_n=G^-1 G_n-sigma_n I.
    Cn=np.einsum('nij,njk->nik',Gi,Gn)-sigman[:,None,None]*np.eye(2)
    Un2=.5*np.einsum('nij,nji->n',Cn,Cn)
    # Tangential speed, needed for |dU(X)| only X normal => |X|sqrt(Un2).
    return dict(q=q,k=k,a=a,an=an,rho=rho,sigma=sigma,sigman=sigman,
                charge=charge,Q=Q,Amat=Amat,Amatn=Amatn,Un2=Un2)


def run(N,L=0.02):
    s,q0,k0,meta=ev.initial_data(N,1,1.0,.5)
    y0=ev.pack_symmetric(q0,k0)
    ns=np.linspace(0,L,81)
    sol=solve_ivp(ev.rhs_factory(N,dealias=True),(0,L),y0,t_eval=ns,method='DOP853',
                  rtol=2e-9,atol=2e-11,max_step=L/100)
    numdens=[]; dendens=[]; raw=[]
    two_pi=2*math.pi
    for n,y in zip(sol.t,sol.y.T):
        d=sample_fields(y,N); ch=cutoff(float(n),L); chp=cutoff_prime(float(n),L)
        # Base metric gamma=a^2 ds^2+dn^2 and X=ch d_n.
        # div X=chp+(a_n/a)ch; div_sigma adds sigma_n ch.
        divx=chp+(d['an']/d['a'])*ch
        divsig=divx+d['sigman']*ch
        # X(Amat)=ch Amat_n. K_X = X(A)+(div_sigma X)A.
        KX=ch*d['Amatn']+divsig[:,None,None]*d['Amat']
        quad=np.einsum('ni,nij,nj->n',d['charge'],KX,d['charge'])
        # dmu_sigma on quotient = rho*dvol_gamma = rho*a ds dn.
        weight=d['rho']*d['a']*(two_pi/N)
        numdens.append(.5*np.sum(quad*weight))
        # invariant coefficient norms. symgrad X has nn=chp and ss=(a_n/a)ch.
        symnorm=np.sqrt(chp**2+((d['an']/d['a'])*ch)**2)
        dUX=np.abs(ch)*np.sqrt(np.maximum(d['Un2'],0))
        den=np.sum((2*symnorm+math.sqrt(2)*np.abs(divsig)+np.abs(divx)+dUX)*weight)
        dendens.append(den)
        raw.append({'n':float(n),'charge_std':float(d['charge'].std(axis=0).max()),
                    'Qmax':float(d['Q'].max()),'num_slice':float(numdens[-1]),
                    'den_slice':float(den)})
    num=abs(np.trapezoid(numdens,sol.t));den=float(np.trapezoid(dendens,sol.t))
    q,k=ev.unpack_symmetric(sol.y[:,-1],N); c=ev.constraints(q,k)
    return {'N':N,'L':L,'success':bool(sol.success),'numerator':float(num),
            'denominator':den,'R_X':float(num/den),'terminal_ham_max':float(abs(c['ham']).max()),
            'terminal_mom_max':float(c['mom_norm'].max()),'selected_slices':[raw[i] for i in (0,20,40,60,80)]}

out={'definition':'R_X=|1/2 int charge^T K_X charge dmu_sigma| / int(2|symgrad X|+sqrt(2)|div_sigma X|+|div X|+|dU(X)|)dmu_sigma',
     'X':'sin^4(pi n/L) partial_n, L=0.02','runs':[run(N) for N in (48,64,96)],
     'continuum_expectation':'For fixed charge and compactly supported X, the numerator is the integral of div_sigma(QX) and vanishes by algebraic integration by parts, independently of Einstein/Noether. This run checks implementation and charge conservation only.',
     'scope':'This tests the same two-variable geometry and adjoint coefficients. It does not prove a global two-end estimate.'}
path=Path('workspace/data/step96_relative_KX_diagnostic.json');path.write_text(json.dumps(out,indent=2))
print(json.dumps(out,indent=2))
