"""
Step 64: Homeomorphism classification of positive-mirror A1-filling rows.

Model.  O = (S^2 x S^2)/Z_2 (diagonal antipodal involution) has 4 A_1
singularities.  Replace each by an Eguchi-Hanson piece; topologically each
filling is the disk bundle O(eps*2) over S^2, eps = -1 (compatible) or
+1 (reversed).  Let r = number of reversed pieces.  M(pattern) is smooth,
simply connected (Step 57 van Kampen), chi = 8, (b_+,b_-) = (1+r, 5-r).

Spin/seam analysis (proof in the accompanying note):
  * RP^3 has exactly two spin structures, distinguished by the Rokhlin
    mu-invariant: mu = +1 or -1 (mod 16).  mu flips sign under orientation
    reversal, and orientation-preserving diffeomorphisms of RP^3 preserve
    each spin structure (pi_0 Diff(RP^3) = Z/2 generated by an
    orientation-reversing isometry; mu is a spin-diffeomorphism invariant).
  * O(eps*2) is spin with a UNIQUE spin structure (H^1(O(eps*2);Z/2) = 0),
    inducing on its boundary RP^3 the spin structure with mu = eps
    (Rokhlin: mu(boundary) == sigma(filling) mod 16).
  * X* = O minus the four A_1 charts is spin (the lift of the diagonal
    involution to the spin bundle of S^2 x S^2 squares to +1) and
    sigma(X*) = 0 (Novikov additivity against the all-compatible
    resolution: sigma(resolution) = -4 = sigma(X*) + 4*(-1)).
  * Filling all four seams spin-compatibly and applying Rokhlin to the
    closed spin manifold gives sigma(X*) == sum_i mu_i (mod 16), forcing
    the seam mu-pattern {+1,+1,-1,-1}: exactly two seams of each type.
  * A spin gluing exists iff each seam is filled spin-compatibly, i.e.
    O(+2) pieces sit exactly on the two seams with mu(boundary of X*) = -1.
    Hence M(pattern) is spin iff r = 2 AND the reversed pair is the
    distinguished pair of seams.  All other patterns are non-spin.

Freedman classification (smooth => Kirby-Siebenmann 0):
  s.c. spin, even unimodular form rank 6 sigma 0  => 3H  => #3(S^2xS^2)
  s.c. non-spin, odd unimodular form (b_+,b_-)    => #_{b_+}CP2 #_{b_+}CP2bar

Consistency anchor: r = 0 gives (1,5) non-spin => #CP2#5CP2bar, which is
exactly the degree-4 del Pezzo diffeotype already known from Step 49.
"""

import json

OUT = "Sessions/S0910A02/workspace/data/step64_positive_mirror_homeomorphism.json"

def mu_seam_split(n_seams, sigma_X):
    """Return (n_plus, n_minus) with n_plus + n_minus = n_seams and
    n_plus - n_minus == sigma_X (mod 16), each mu_i in {+1,-1}."""
    sols = []
    for n_plus in range(n_seams + 1):
        n_minus = n_seams - n_plus
        if (n_plus - n_minus - sigma_X) % 16 == 0:
            sols.append((n_plus, n_minus))
    return sols

def homeotype(b_plus, b_minus, spin):
    if spin:
        assert b_plus == b_minus, "even unimodular needs sigma = 0 mod 8; here sigma=0"
        k = b_plus
        return {"type": f"#{k}(S2xS2)", "form": f"{k}H", "parity": "even", "spin": True}
    else:
        return {"type": f"#{b_plus}CP2#{b_minus}CP2bar",
                "form": f"{b_plus}<1> + {b_minus}<-1>", "parity": "odd", "spin": False}

# ---- seam split for the Z2 family (4 seams, sigma(X*) = 0) ----
split_Z2 = mu_seam_split(4, 0)
assert split_Z2 == [(2, 2)], split_Z2

# ---- classification table, r = number of reversed (O(+2)) pieces ----
rows = []
for r in range(5):
    b_plus, b_minus = 1 + r, 5 - r
    # spin iff r equals the number of (-1)-seams (=2) AND the reversed pair
    # is exactly the distinguished pair.  Both subset choices exist for r=2.
    if r == 2:
        spin_options = [True, False]
    else:
        spin_options = [False]
    for spin in spin_options:
        ht = homeotype(b_plus, b_minus, spin)
        rows.append({
            "r": r,
            "b_plus": b_plus,
            "b_minus": b_minus,
            "spin": spin,
            "homeomorphism_type": ht["type"],
            "intersection_form": ht["form"],
            "sigma": b_plus - b_minus,
            "chi": 2 + b_plus + b_minus,
            "strict_HT": (2 + b_plus + b_minus) > 1.5 * abs(b_plus - b_minus),
            "SW_vanish": (b_plus >= 2),   # connected sum of b_+>=1 pieces
            "PSC": True,                   # connected sum of PSC pieces (GL surgery)
            "einstein_status": "OPEN (SW-void, non-Kahler, PSC, strict HT)"
                               if spin or (2 <= b_plus) else
                               ("KNOWN: degree-4 del Pezzo, positive KE exists"
                                if r == 0 else "KNOWN: orientation reverse of del Pezzo"),
        })

# consistency anchor: r=0 must be the degree-4 del Pezzo
r0 = [x for x in rows if x["r"] == 0][0]
assert r0["homeomorphism_type"] == "#1CP2#5CP2bar"
assert r0["spin"] is False

# ---- V4 analog: 6 seams, sigma(X*_V) = 0 (Novikov: -6 = sigma + 6*(-1)) ----
split_V4 = mu_seam_split(6, 0)
assert split_V4 == [(3, 3)], split_V4
v4_balanced_spin = homeotype(4, 4, True)

# ---- Rokhlin consistency for closed spin gluings ----
def closed_sigma(sigma_X, eps_list):
    return sigma_X + sum(eps_list)
assert closed_sigma(0, [+1, +1, -1, -1]) % 16 == 0     # balanced special: OK
assert closed_sigma(0, [-1, -1, -1, -1]) % 16 != 0     # all-compatible: not spin
assert closed_sigma(0, [+1]*3 + [-1]*3) % 16 == 0      # V4 balanced: OK

# ---- Diff(RP^3) preservation ledger ----
diff_rp3 = {
    "pi0_Diff(RP3)": "Z/2 (Hatcher), generated by an orientation-reversing isometry",
    "action_on_H1": "trivial (Aut(Z/2) is trivial)",
    "orientation_preserving_preserves_spin_structures": True,
    "reason": "connected o.p. component acts trivially on the 2-element set; "
              "mu is orientation-sensitive so no o.p. diffeo swaps mu=+1 and mu=-1",
    "consequence": "gluing diffeomorphisms cannot repair a seam spin mismatch",
}

summary = {
    "seam_split_Z2_family": {"seams": 4, "mu_pattern": [1, 1, -1, -1],
                             "rule": "O(+2) reversed pieces must sit on the two mu=-1 seams"},
    "seam_split_V4_family": {"seams": 6, "mu_pattern": [1, 1, 1, -1, -1, -1]},
    "rows": rows,
    "merge": {
        "spin_balanced_row": "#3(S2xS2) homeomorphism type",
        "step9_stress_family_member": "k=3",
        "status": "homeomorphic (Freedman); diffeomorphism to the standard "
                  "smooth #3(S2xS2) is OPEN (exotic structures not excluded)",
    },
    "V4_balanced_spin": v4_balanced_spin,
    "diff_rp3": diff_rp3,
    "open_bit": "which symmetry class of balanced pairs (adjacent vs diagonal) is "
                "the distinguished mu=-1 pair requires the explicit induced-spin "
                "computation at one seam; BOTH smooth types are realizable regardless",
    "einstein_status_all_mixed_rows": "OPEN: simply connected, PSC, strict HT, "
                                      "SW vanish (b_+>=2), non-Kahler both orientations",
}

with open(OUT, "w") as f:
    json.dump(summary, f, indent=2)

print(json.dumps({"status": "ok", "output": OUT,
                  "rows": [(x["r"], x["spin"], x["homeomorphism_type"]) for x in rows],
                  "merge": summary["merge"]["spin_balanced_row"]}, indent=2))
