# Topological arithmetic: compare spin/intersection forms of #_k(S2xS2) with rational/log del Pezzo resolutions.
# Smooth rational complex surfaces have b1=0 and intersection form either <1> ⊕ m<-1>
# (CP2 blowups) or H ⊕ m<-1> (S2xS2/Hirzebruch even base blowups). Spin iff the form is even;
# H is even, while adding any <-1> makes odd.  #_k(S2xS2) has kH, even, b2=2k, tau=0.

def is_form_even(diag: List[int], hyperbolic_blocks: int = 0) -> bool:
    # Diagonal <-1> or <1> gives odd vector square; H blocks alone are even.
    return all(x % 2 == 0 for x in diag)


