#!/usr/bin/env python3
"""Step 98: integral gluing of a Wahl ball into X#k CPbar^2 -- the lattice condition is vacuous for k >= 5.

Mathematical setting (proved in notes/step96_suvaina_lattice_and_kahler_filler_theorem.md, Sec. 3, Prop. 98.W):
for a Wahl ball B=B_{n,a} (H_1=Z_n, H_2=0, boundary L(n^2, na-1)) in M=X#kCPbar^2 with pi_1(X) torsion-free,
the complement W has H_2(W) -> H_2(M) injective with cokernel Z_n, torsion carried isomorphically, so the free
lattice L=H_2(W)/Tor has index n in U=H_2(M)/Tor and |L^*/L|=n^2; with Tor H_1(X)=0, L^*/L is cyclic of order
n^2 with discriminant bilinear form = -/+ (linking form of the lens space) depending on orientation.

This script checks the *realizability* half: for every n<=NMAX, every a coprime to n, both orientation signs
sigma, it constructs a primitive v in -I_5 with  v.v = -N,  N == -sigma*(na-1)*u^2 (mod n^2) for some unit u,
forms L_v = {x in Z^5 : x.v == 0 mod n}, computes its Gram matrix, its Smith normal form, and verifies that
L_v^*/L_v is cyclic of order n^2 generated by v/n with self-pairing -N/n^2 == sigma*(na-1)u^2/n^2 mod 1.
Output: workspace/data/step98/wahl_gluing_lattice.json.
It is a finite consistency check of the elementary construction in the note; the general statement is the proof there.
"""
import itertools, json, math, os
from fractions import Fraction
import sympy as sp
from sympy.matrices.normalforms import smith_normal_form

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "data", "step98", "wahl_gluing_lattice.json")
NMAX = 9
K = 5


def four_squares(m):
    for a in range(int(math.isqrt(m)) + 1):
        for b in range(a, int(math.isqrt(m - a * a)) + 1):
            for c in range(b, int(math.isqrt(m - a * a - b * b)) + 1):
                r = m - a * a - b * b - c * c
                d = math.isqrt(r)
                if d * d == r and d >= c:
                    return [a, b, c, d]
    return None


def basis_Lv(v, n):
    """Z-basis of {x in Z^K : x.v' == 0 mod n} where the form is -I, so x.v = -sum x_i v_i; v_0 = 1."""
    # v[0]=1: x_0 determined mod n by the others. Basis: n e_0, and e_i - v_i e_0 for i>=1.
    B = []
    e0 = [n] + [0] * (K - 1)
    B.append(e0)
    for i in range(1, K):
        b = [0] * K
        b[i] = 1
        b[0] = -v[i]
        B.append(b)
    return sp.Matrix(B)


def run():
    rows = []
    allok = True
    for n in range(2, NMAX + 1):
        for a in range(1, n):
            if math.gcd(a, n) != 1:
                continue
            q = n * a - 1
            for sigma in (1, -1):
                found = None
                units = [u for u in range(1, n * n) if math.gcd(u, n) == 1]
                for N in range(1, 4 * n * n + 2):
                    if any((N + sigma * q * u * u) % (n * n) == 0 for u in units):
                        fs = four_squares(N - 1)
                        if fs is not None:
                            found = (N, [1] + fs)
                            break
                N, v = found
                assert sum(t * t for t in v) == N
                B = basis_Lv(v, n)
                G = -B * B.T  # Gram of L_v in the -I_K form
                # check every basis vector is in L_v
                for r in range(K):
                    assert sum(B[r, i] * v[i] for i in range(K)) % n == 0
                det = G.det()
                snf = smith_normal_form(G, domain=sp.ZZ)
                inv = sorted(abs(snf[i, i]) for i in range(K))
                cyclic = inv[:-1] == [1] * (K - 1) and inv[-1] == n * n
                # self-pairing of v/n: (v/n).(v/n) = -N/n^2
                q_val = Fraction(-N, n * n) % 1
                target = {Fraction(sigma * q * u * u, n * n) % 1 for u in units}
                ok = abs(det) == n * n and cyclic and q_val in target
                allok &= ok
                rows.append(dict(n=n, a=a, q=q, sigma=sigma, N=N, v=v, det=int(det), snf=[int(t) for t in inv],
                                 cyclic=cyclic, self_pairing=str(q_val), ok=ok))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(dict(K=K, NMAX=NMAX, all_ok=allok, cases=len(rows), rows=rows), f, indent=1)
    print(len(rows), "cases; all_ok =", allok)
    assert allok


if __name__ == "__main__":
    run()
